//! `cargo xtask feature-tests` — every test runs in some CI pass.
//!
//! Main's suite is `cargo nextest run --workspace`: each member with its
//! default features, unified with what the other members (and their
//! dev-dependencies) turn on. A test that needs more than that never
//! builds there, and nothing says so: `reconnect_supervisor` (#299) sat
//! broken behind `required-features` no member enabled. So this resolves
//! that build with guppy (cargo's resolver v2, dev-dependencies on,
//! `x86_64-unknown-linux-gnu`) and finds every test it leaves out:
//!
//! - a `[[test]]` target whose `required-features` the build lacks;
//! - a test behind a `cfg(…feature…)` that is false there: a target's
//!   `#![cfg(…)]`, a module declared under `#[cfg(…)]` (`mod keyflow;`),
//!   an inline `mod tests` or a `#[test]` fn with its own `#[cfg(…)]`.
//!
//! Each must be run by a pass in `feature-tests.toml` (a `cargo nextest
//! run -p … --features …` of its own, resolved the same way) or listed
//! there as a `[[skip]]` with its reason. A new gap, a pass that runs
//! nothing the workspace run does not, and a skip that no longer matches
//! fail the check. `--run` runs the passes (CI's Tests job).
//!
//! Known blind spots, kept simple on purpose: a `#[cfg(feature)]` on an
//! inline module that is neither `tests` nor `cfg(test)` (its tests are
//! not seen), `#[cfg_attr(…, test)]`, and tests generated by macros.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

use guppy::graph::cargo::{CargoOptions, CargoResolverVersion};
use guppy::graph::feature::{FeatureId, StandardFeatures, feature_id_filter};
use guppy::graph::{BuildTargetId, DependencyDirection, PackageGraph, PackageMetadata};
use guppy::platform::{Platform, TargetFeatures};
use serde::Deserialize;

/// The platform main's suite runs on.
const TRIPLE: &str = "x86_64-unknown-linux-gnu";
/// The workspace run's name in reports.
const WORKSPACE: &str = "workspace";

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Config {
    #[serde(default)]
    pass: Vec<Pass>,
    #[serde(default)]
    skip: Vec<Skip>,
}

/// One extra `cargo nextest run`: these packages, these features.
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Pass {
    name: String,
    packages: Vec<String>,
    /// `package/feature`, as `cargo --features` takes them.
    #[serde(default)]
    features: Vec<String>,
    /// Set for this pass's run (`ARCHITECT_WASI_REQUIRED`, …).
    #[serde(default)]
    env: BTreeMap<String, String>,
    /// Build the whole workspace with these features (`--workspace`) and
    /// run only `packages`' tests: for a member near the top of the graph,
    /// where `-p` alone would resolve the members under it with fewer
    /// features than the workspace run and so build them all again.
    #[serde(default)]
    workspace: bool,
}

/// A gated test no pass runs, on purpose.
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Skip {
    package: String,
    /// The test's file, relative to the package's folder.
    file: String,
    reason: String,
}

/// A build: which members it tests and every member's resolved features.
struct Build {
    name: String,
    selected: BTreeSet<String>,
    features: BTreeMap<String, BTreeSet<String>>,
}

impl Build {
    fn builds(&self, package: &str, required: &[String]) -> bool {
        self.selected.contains(package)
            && self
                .features
                .get(package)
                .is_some_and(|have| required.iter().all(|f| have.contains(f)))
    }
}

/// A test that needs features: a whole target, or a cfg'd part of one.
struct Gated {
    package: String,
    /// The target's name (`lib`, `bin:x`, `test:x`).
    target: String,
    required: Vec<String>,
    /// Relative to the package's folder.
    file: String,
    /// The cfg chain from the target's root down to the test; empty for a
    /// target gated only by `required-features`.
    cond: Vec<Cfg>,
    lines: BTreeSet<usize>,
}

impl Gated {
    fn describe(&self) -> String {
        let mut what = format!("{} {} ({})", self.package, self.file, self.target);
        if !self.required.is_empty() {
            let _ = write!(what, " required-features {:?}", self.required);
        }
        let cfgs: Vec<_> = self
            .cond
            .iter()
            .filter(|c| c.has_feature())
            .map(Cfg::to_string)
            .collect();
        if !cfgs.is_empty() {
            let lines: Vec<_> = self.lines.iter().map(usize::to_string).collect();
            let _ = write!(
                what,
                " cfg {} (line {})",
                cfgs.join(" & "),
                lines.join(", ")
            );
        }
        what
    }

    fn runs_in(&self, build: &Build) -> bool {
        build.builds(&self.package, &self.required)
            && build
                .features
                .get(&self.package)
                .is_some_and(|f| self.cond.iter().all(|c| c.eval(f)))
    }
}

pub fn run_cli(
    root: &Path,
    config: &Path,
    list: bool,
    run: bool,
    filter: Option<&str>,
    extra: &[String],
) -> Result<(), String> {
    let text = std::fs::read_to_string(root.join(config))
        .map_err(|e| format!("{}: {e}", config.display()))?;
    let config: Config = toml::from_str(&text).map_err(|e| format!("{}: {e}", config.display()))?;
    let graph = crate::fleet_deps::load(root, false)?;
    let builds = builds(&graph, &config)?;
    let gated = gated(&graph)?;

    let mut problems = Vec::new();
    let mut used_skips = BTreeSet::new();
    let mut useful = BTreeSet::new();
    for g in &gated {
        let by: Vec<_> = builds.iter().filter(|b| g.runs_in(b)).collect();
        let skip = config
            .skip
            .iter()
            .enumerate()
            .find(|(_, s)| s.package == g.package && s.file == g.file);
        let status = match (by.first(), skip) {
            (Some(first), _) => {
                if first.name != WORKSPACE {
                    for b in &by {
                        useful.insert(b.name.clone());
                    }
                }
                by.iter()
                    .map(|b| b.name.as_str())
                    .collect::<Vec<_>>()
                    .join(",")
            }
            (None, Some((i, s))) => {
                used_skips.insert(i);
                format!("skip ({})", s.reason)
            }
            (None, None) => {
                problems.push(format!("not run by any pass: {}", g.describe()));
                "NONE".to_owned()
            }
        };
        if list {
            println!("{status:<12} {}", g.describe());
        }
    }
    for (i, s) in config.skip.iter().enumerate() {
        if !used_skips.contains(&i) {
            problems.push(format!(
                "stale [[skip]] {} {}: no unrun gated test there (now run, or moved)",
                s.package, s.file
            ));
        }
    }
    for p in &config.pass {
        if !useful.contains(&p.name) {
            problems.push(format!(
                "pass `{}` runs no gated test the workspace run leaves out",
                p.name
            ));
        }
    }
    if !problems.is_empty() {
        for p in &problems {
            eprintln!("{p}");
        }
        return Err(format!(
            "{} problem(s); add a [[pass]] (or a [[skip]] with its reason) to feature-tests.toml",
            problems.len()
        ));
    }
    println!(
        "feature-tests: {} gated test(s), {} pass(es), {} skip(s): every one runs or says why",
        gated.len(),
        config.pass.len(),
        config.skip.len()
    );
    if run {
        run_passes(root, &config, filter, extra)?;
    }
    Ok(())
}

fn run_passes(
    root: &Path,
    config: &Config,
    filter: Option<&str>,
    extra: &[String],
) -> Result<(), String> {
    let cargo = std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into());
    let mut failed = Vec::new();
    for pass in &config.pass {
        let mut cmd = Command::new(&cargo);
        cmd.current_dir(root).args(["nextest", "run"]);
        let mut exprs: Vec<String> = filter.map(|f| format!("({f})")).into_iter().collect();
        if pass.workspace {
            cmd.arg("--workspace");
            let own: Vec<_> = pass
                .packages
                .iter()
                .map(|p| format!("package(={p})"))
                .collect();
            exprs.push(format!("({})", own.join(" | ")));
        } else {
            for p in &pass.packages {
                cmd.args(["-p", p]);
            }
        }
        if !exprs.is_empty() {
            cmd.args(["-E", &exprs.join(" & ")]);
        }
        if !pass.features.is_empty() {
            cmd.args(["--features", &pass.features.join(",")]);
        }
        cmd.args(extra).envs(&pass.env);
        // `cargo run -p xtask` sets these for xtask itself; the passes'
        // builds should see the environment the workspace run did.
        for (key, _) in std::env::vars_os() {
            let k = key.to_string_lossy();
            if k.starts_with("CARGO_PKG_")
                || matches!(
                    &*k,
                    "CARGO_MANIFEST_DIR"
                        | "CARGO_MANIFEST_PATH"
                        | "CARGO_CRATE_NAME"
                        | "CARGO_BIN_NAME"
                        | "CARGO_PRIMARY_PACKAGE"
                )
            {
                cmd.env_remove(&key);
            }
        }
        println!(
            "== pass `{}`: {:?}",
            pass.name,
            cmd.get_args().collect::<Vec<_>>()
        );
        let start = std::time::Instant::now();
        let ok = cmd.status().is_ok_and(|s| s.success());
        println!(
            "== pass `{}`: {} in {:.0?}",
            pass.name,
            if ok { "ok" } else { "FAILED" },
            start.elapsed()
        );
        if !ok {
            failed.push(pass.name.clone());
        }
    }
    if failed.is_empty() {
        Ok(())
    } else {
        Err(format!("pass(es) failed: {}", failed.join(", ")))
    }
}

/// The workspace run, then each pass.
fn builds(graph: &PackageGraph, config: &Config) -> Result<Vec<Build>, String> {
    let members: Vec<_> = graph.workspace().iter().collect();
    let mut out = vec![resolve(graph, WORKSPACE, &members, &[], None)?];
    for pass in &config.pass {
        let mut selected = Vec::new();
        for name in &pass.packages {
            let pkg = graph
                .workspace()
                .member_by_name(name)
                .map_err(|_| format!("pass `{}`: no member `{name}`", pass.name))?;
            selected.push(pkg);
        }
        let mut extra = Vec::new();
        for spec in &pass.features {
            let (pkg, feature) = spec.split_once('/').ok_or_else(|| {
                format!("pass `{}`: `{spec}` is not `package/feature`", pass.name)
            })?;
            let meta = selected.iter().find(|p| p.name() == pkg).ok_or_else(|| {
                format!(
                    "pass `{}`: `{spec}`: `{pkg}` is not in its packages",
                    pass.name
                )
            })?;
            if !meta.named_features().any(|f| f == feature) {
                return Err(format!(
                    "pass `{}`: `{pkg}` has no feature `{feature}`",
                    pass.name
                ));
            }
            extra.push((meta.id(), feature));
        }
        out.push(if pass.workspace {
            resolve(graph, &pass.name, &members, &extra, Some(&selected))?
        } else {
            resolve(graph, &pass.name, &selected, &extra, None)?
        });
    }
    Ok(out)
}

fn resolve(
    graph: &PackageGraph,
    name: &str,
    selected: &[PackageMetadata<'_>],
    extra: &[(&guppy::PackageId, &str)],
    tested: Option<&[PackageMetadata<'_>]>,
) -> Result<Build, String> {
    let platform = Platform::new(TRIPLE, TargetFeatures::Unknown).map_err(|e| e.to_string())?;
    let mut opts = CargoOptions::new();
    opts.set_resolver(CargoResolverVersion::V2)
        .set_include_dev(true)
        .set_target_platform(platform.clone())
        .set_host_platform(platform);
    let ids: Vec<_> = selected
        .iter()
        .map(guppy::graph::PackageMetadata::id)
        .collect();
    let initials = graph
        .resolve_ids(ids.iter().copied())
        .map_err(|e| e.to_string())?
        .to_feature_set(feature_id_filter(
            StandardFeatures::Default,
            extra.iter().map(|(id, f)| FeatureId::named(id, f)),
        ));
    let set = initials
        .into_cargo_set(&opts)
        .map_err(|e| format!("resolving `{name}`: {e}"))?;
    // Proc macros (and build-time deps) are the host's; on this platform
    // host and target are one machine, and a member's tests build either.
    let mut features: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for side in [set.target_features(), set.host_features()] {
        for list in side.packages_with_features(DependencyDirection::Forward) {
            if list.package().in_workspace() {
                features
                    .entry(list.package().name().to_owned())
                    .or_default()
                    .extend(list.named_features().map(str::to_owned));
            }
        }
    }
    Ok(Build {
        name: name.to_owned(),
        selected: tested
            .unwrap_or(selected)
            .iter()
            .map(|p| p.name().to_owned())
            .collect(),
        features,
    })
}

/// Every gated test in the workspace's members.
fn gated(graph: &PackageGraph) -> Result<Vec<Gated>, String> {
    let mut out: Vec<Gated> = Vec::new();
    for pkg in graph.workspace().iter() {
        let dir = pkg
            .manifest_path()
            .parent()
            .ok_or("manifest without a folder")?
            .as_std_path()
            .to_owned();
        for target in pkg.build_targets() {
            let label = match target.id() {
                BuildTargetId::Library => "lib".to_owned(),
                BuildTargetId::Binary(n) => format!("bin:{n}"),
                BuildTargetId::Test(n) => format!("test:{n}"),
                _ => continue,
            };
            if !target.test_by_default() && !matches!(target.id(), BuildTargetId::Test(_)) {
                continue;
            }
            let required: Vec<String> = target.required_features().to_vec();
            let root = target.path().as_std_path().to_owned();
            let rel = |p: &Path| {
                p.strip_prefix(&dir)
                    .unwrap_or(p)
                    .to_string_lossy()
                    .replace('\\', "/")
            };
            if !required.is_empty() {
                out.push(Gated {
                    package: pkg.name().to_owned(),
                    target: label.clone(),
                    required: required.clone(),
                    file: rel(&root),
                    cond: Vec::new(),
                    lines: BTreeSet::new(),
                });
            }
            let mut sites = Vec::new();
            walk(&root, true, Vec::new(), &mut sites, &mut BTreeSet::new());
            for (file, line, cond) in sites {
                if !cond.iter().any(Cfg::has_feature) {
                    continue;
                }
                let file = rel(&file);
                let key = cond.iter().map(Cfg::to_string).collect::<Vec<_>>();
                if let Some(g) = out.iter_mut().find(|g| {
                    g.package == pkg.name()
                        && g.target == label
                        && g.file == file
                        && g.cond.iter().map(Cfg::to_string).collect::<Vec<_>>() == key
                }) {
                    g.lines.insert(line);
                } else {
                    out.push(Gated {
                        package: pkg.name().to_owned(),
                        target: label.clone(),
                        required: required.clone(),
                        file,
                        cond,
                        lines: BTreeSet::from([line]),
                    });
                }
            }
        }
    }
    Ok(out)
}

/// Walk a module tree from `file`, collecting each test site with the cfg
/// chain that reaches it.
fn walk(
    file: &Path,
    is_root: bool,
    chain: Vec<Cfg>,
    out: &mut Vec<(PathBuf, usize, Vec<Cfg>)>,
    seen: &mut BTreeSet<PathBuf>,
) {
    if !seen.insert(file.to_owned()) {
        return;
    }
    let Ok(text) = std::fs::read_to_string(file) else {
        return;
    };
    let scan = scan(&text);
    let mut chain = chain;
    chain.extend(scan.inner);
    for (line, cfgs) in scan.sites {
        let mut cond = chain.clone();
        cond.extend(cfgs);
        out.push((file.to_owned(), line, cond));
    }
    let parent = file.parent().unwrap_or_else(|| Path::new("."));
    let own_dir = if is_root || file.file_name().is_some_and(|n| n == "mod.rs") {
        parent.to_owned()
    } else {
        parent.join(file.file_stem().unwrap_or_default())
    };
    for m in scan.mods {
        let candidates = match &m.path {
            Some(p) => vec![parent.join(p)],
            None => vec![
                own_dir.join(format!("{}.rs", m.name)),
                own_dir.join(&m.name).join("mod.rs"),
            ],
        };
        if let Some(child) = candidates.into_iter().find(|c| c.is_file()) {
            let mut cond = chain.clone();
            cond.extend(m.cfgs);
            walk(&child, false, cond, out, seen);
        }
    }
}

struct ModDecl {
    name: String,
    path: Option<String>,
    cfgs: Vec<Cfg>,
}

#[derive(Default)]
struct Scan {
    /// `#![cfg(…)]`: the whole file.
    inner: Vec<Cfg>,
    mods: Vec<ModDecl>,
    /// (line, the item's own cfgs) of each test fn and test module.
    sites: Vec<(usize, Vec<Cfg>)>,
}

/// One file's attributes, line by line. Attributes rustfmt wraps over
/// several lines are joined first.
fn scan(text: &str) -> Scan {
    let mut out = Scan::default();
    let mut cfgs: Vec<Cfg> = Vec::new();
    let mut path: Option<String> = None;
    let mut is_test = false;
    let mut lines = text.lines().enumerate();
    while let Some((i, raw)) = lines.next() {
        // A raw string's lines (a fixture, a golden) are not code.
        if let Some((_, after)) = raw.split_once("r#\"") {
            if !after.contains("\"#") {
                for (_, more) in lines.by_ref() {
                    if more.contains("\"#") {
                        break;
                    }
                }
                continue;
            }
        }
        let mut line = raw.trim().to_owned();
        if line.starts_with("#[") || line.starts_with("#![") {
            while depth(&line) > 0 {
                match lines.next() {
                    Some((_, more)) => line.push_str(more.trim()),
                    None => break,
                }
            }
            if let Some(body) = attr_body(&line, "#![cfg(") {
                out.inner.extend(Cfg::parse(body));
            } else if let Some(body) = attr_body(&line, "#[cfg(") {
                cfgs.extend(Cfg::parse(body));
            } else if let Some(rest) = line.strip_prefix("#[path") {
                path = rest.split('"').nth(1).map(str::to_owned);
            } else if is_test_attr(&line) {
                is_test = true;
            }
            continue;
        }
        if line.is_empty() || line.starts_with("//") {
            continue;
        }
        let item = strip_vis(&line);
        if let Some(rest) = item.strip_prefix("mod ") {
            let end = rest
                .find(|c: char| !(c.is_alphanumeric() || c == '_'))
                .unwrap_or(rest.len());
            let (name, after) = rest.split_at(end);
            let (name, after) = (name.to_owned(), after.trim_start());
            if after.starts_with(';') {
                out.mods.push(ModDecl {
                    name,
                    path: path.take(),
                    cfgs: std::mem::take(&mut cfgs),
                });
            } else if after.starts_with('{') && (name == "tests" || cfgs.iter().any(Cfg::has_test))
            {
                out.sites
                    .push((i.saturating_add(1), std::mem::take(&mut cfgs)));
            }
        } else if is_test {
            out.sites
                .push((i.saturating_add(1), std::mem::take(&mut cfgs)));
        }
        cfgs.clear();
        path = None;
        is_test = false;
    }
    out
}

/// Unclosed `[` in an attribute (outside its string literals).
fn depth(line: &str) -> i32 {
    let mut d = 0;
    let mut in_str = false;
    let mut prev = ' ';
    for c in line.chars() {
        match c {
            '"' if prev != '\\' => in_str = !in_str,
            '[' if !in_str => d = i32::saturating_add(d, 1),
            ']' if !in_str => d = i32::saturating_sub(d, 1),
            _ => {}
        }
        prev = c;
    }
    d
}

fn attr_body<'a>(line: &'a str, prefix: &str) -> Option<&'a str> {
    let rest = line.strip_prefix(prefix)?;
    rest.rsplit_once(")]").map(|(body, _)| body)
}

/// `#[test]`, `#[tokio::test]`, `#[tokio::test(flavor = …)]`, `#[rstest]`,
/// `#[test_case(…)]`: a fn nextest runs natively (not `wasm_bindgen_test`).
fn is_test_attr(line: &str) -> bool {
    let Some(inner) = line.strip_prefix("#[") else {
        return false;
    };
    let path: String = inner
        .chars()
        .take_while(|c| c.is_alphanumeric() || *c == '_' || *c == ':')
        .collect();
    let last = path.rsplit("::").next().unwrap_or("");
    matches!(last, "test" | "rstest" | "test_case")
}

fn strip_vis(line: &str) -> &str {
    let Some(rest) = line.strip_prefix("pub") else {
        return line;
    };
    let rest = rest.trim_start();
    rest.strip_prefix('(').map_or(rest, |after| {
        after.split_once(')').map_or(rest, |(_, r)| r.trim_start())
    })
}

/// A `cfg(…)` predicate.
#[derive(Clone, Debug, PartialEq)]
enum Cfg {
    All(Vec<Self>),
    Any(Vec<Self>),
    Not(Box<Self>),
    Feature(String),
    /// `key` or `key = "value"`.
    Key(String, Option<String>),
}

impl Cfg {
    fn parse(body: &str) -> Option<Self> {
        let tokens = tokenize(body);
        let mut it = tokens.iter().peekable();
        let cfg = parse_pred(&mut it)?;
        it.next().is_none().then_some(cfg)
    }

    fn has_feature(&self) -> bool {
        match self {
            Self::All(v) | Self::Any(v) => v.iter().any(Self::has_feature),
            Self::Not(c) => c.has_feature(),
            Self::Feature(_) => true,
            Self::Key(..) => false,
        }
    }

    fn has_test(&self) -> bool {
        match self {
            Self::All(v) | Self::Any(v) => v.iter().any(Self::has_test),
            Self::Not(c) => c.has_test(),
            Self::Feature(_) => false,
            Self::Key(k, v) => k == "test" && v.is_none(),
        }
    }

    /// True in a native Linux `x86_64` test build with these features.
    fn eval(&self, features: &BTreeSet<String>) -> bool {
        match self {
            Self::All(v) => v.iter().all(|c| c.eval(features)),
            Self::Any(v) => v.iter().any(|c| c.eval(features)),
            Self::Not(c) => !c.eval(features),
            Self::Feature(f) => features.contains(f),
            Self::Key(k, None) => matches!(k.as_str(), "test" | "unix" | "debug_assertions"),
            Self::Key(k, Some(v)) => matches!(
                (k.as_str(), v.as_str()),
                ("target_os", "linux")
                    | ("target_family", "unix")
                    | ("target_arch", "x86_64")
                    | ("target_env", "gnu")
                    | ("target_pointer_width", "64")
                    | ("target_endian", "little")
                    | ("target_vendor", "unknown")
                    | ("panic", "unwind")
            ),
        }
    }
}

impl std::fmt::Display for Cfg {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let list = |f: &mut std::fmt::Formatter<'_>, name: &str, v: &[Self]| {
            let parts: Vec<_> = v.iter().map(Self::to_string).collect();
            write!(f, "{name}({})", parts.join(", "))
        };
        match self {
            Self::All(v) => list(f, "all", v),
            Self::Any(v) => list(f, "any", v),
            Self::Not(c) => write!(f, "not({c})"),
            Self::Feature(n) => write!(f, "feature = \"{n}\""),
            Self::Key(k, None) => write!(f, "{k}"),
            Self::Key(k, Some(v)) => write!(f, "{k} = \"{v}\""),
        }
    }
}

#[derive(Debug, PartialEq)]
enum Tok {
    Ident(String),
    Str(String),
    Open,
    Close,
    Comma,
    Eq,
}

fn tokenize(s: &str) -> Vec<Tok> {
    let mut out = Vec::new();
    let mut chars = s.chars().peekable();
    while let Some(&c) = chars.peek() {
        match c {
            '(' => {
                out.push(Tok::Open);
                chars.next();
            }
            ')' => {
                out.push(Tok::Close);
                chars.next();
            }
            ',' => {
                out.push(Tok::Comma);
                chars.next();
            }
            '=' => {
                out.push(Tok::Eq);
                chars.next();
            }
            '"' => {
                chars.next();
                let mut v = String::new();
                for c in chars.by_ref() {
                    if c == '"' {
                        break;
                    }
                    v.push(c);
                }
                out.push(Tok::Str(v));
            }
            c if c.is_alphanumeric() || c == '_' => {
                let mut v = String::new();
                while let Some(&c) = chars.peek() {
                    if c.is_alphanumeric() || c == '_' {
                        v.push(c);
                        chars.next();
                    } else {
                        break;
                    }
                }
                out.push(Tok::Ident(v));
            }
            _ => {
                chars.next();
            }
        }
    }
    out
}

type Toks<'a> = std::iter::Peekable<std::slice::Iter<'a, Tok>>;

fn parse_pred(it: &mut Toks<'_>) -> Option<Cfg> {
    let Some(Tok::Ident(name)) = it.next() else {
        return None;
    };
    match it.peek() {
        Some(Tok::Open) => {
            it.next();
            let mut args = Vec::new();
            loop {
                match it.peek() {
                    Some(Tok::Close) => {
                        it.next();
                        break;
                    }
                    Some(Tok::Comma) => {
                        it.next();
                    }
                    Some(_) => args.push(parse_pred(it)?),
                    None => return None,
                }
            }
            match name.as_str() {
                "all" => Some(Cfg::All(args)),
                "any" => Some(Cfg::Any(args)),
                "not" => args.into_iter().next().map(|c| Cfg::Not(Box::new(c))),
                _ => None,
            }
        }
        Some(Tok::Eq) => {
            it.next();
            let Some(Tok::Str(v)) = it.next() else {
                return None;
            };
            Some(if name == "feature" {
                Cfg::Feature(v.clone())
            } else {
                Cfg::Key(name.clone(), Some(v.clone()))
            })
        }
        _ => Some(Cfg::Key(name.clone(), None)),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cfg_parses_and_evaluates_natively() {
        let c = Cfg::parse(
            r#"all(feature = "local", feature = "telemetry", not(target_arch = "wasm32"))"#,
        )
        .unwrap();
        let on: BTreeSet<_> = ["local", "telemetry"].map(str::to_owned).into();
        assert!(c.eval(&on));
        assert!(!c.eval(&BTreeSet::from(["local".to_owned()])));
        assert!(c.has_feature() && !c.has_test());
        assert!(
            Cfg::parse("all(test, unix)")
                .unwrap()
                .eval(&BTreeSet::new())
        );
        assert!(!Cfg::parse("windows").unwrap().eval(&BTreeSet::new()));
    }

    #[test]
    fn scan_finds_gated_modules_and_tests() {
        let src = r#"
#![cfg(feature = "a")]
#[cfg(feature = "b")]
mod keyflow;
#[cfg(all(
    test,
    feature = "c"
))]
mod tests {
    #[tokio::test(flavor = "multi_thread")]
    async fn t() {}
}
#[cfg(feature = "d")]
#[test]
fn u() {}
#[wasm_bindgen_test]
fn w() {}
"#;
        let s = scan(src);
        assert_eq!(s.inner, vec![Cfg::Feature("a".into())]);
        assert_eq!(s.mods.len(), 1);
        assert_eq!(s.mods[0].cfgs, vec![Cfg::Feature("b".into())]);
        let lines: Vec<_> = s.sites.iter().map(|(l, _)| *l).collect();
        assert_eq!(lines, vec![9, 11, 15]);
        assert_eq!(s.sites[2].1, vec![Cfg::Feature("d".into())]);
    }
}
