// TypeScript extensions (#536): `kind = "typescript"`, actions and hooks
// as `.ts` modules beside TSX pages, run by the app on its pages' runtime.
// What `architect-ext` does for one:
//
// - `scaffold`: a new one (a manifest, one action, one page, a tsconfig);
// - `writeTypes`: `types/architect.d.ts` (the app's runtime, generated
//   from its services: features/pages/types/architect.d.ts) and
//   `types/actions.d.ts` (each action's arguments from its manifest's
//   `params`, typegen.mjs's `schemaType`, as `ActionArgs`);
// - `check`: the manifest (a typescript extension's rules, as
//   `Manifest::check` has them) and its files, then `tsc --noEmit`;
// - `pack` and `sign`: the `.archext` the app installs, the format of
//   features/extensions/archive (`pack`, `sign::SecretKey::sign`): a
//   gzipped tar of `archext.json` (every file's size and SHA-256), its
//   minisign signature `archext.json.minisig`, and the files.
import { createHash, createPrivateKey, randomBytes, sign as edSign, createPublicKey } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
import { parse } from 'smol-toml';
import { actionPrefix, checkManifest } from './manifest.mjs';
import { schemaType } from './typegen.mjs';

const here = dirname(fileURLToPath(import.meta.url));

/// What a typescript extension's actions and hooks may be.
const SCRIPT = /\.(ts|mts|tsx|js|mjs|jsx)$/;

/// The app's runtime types: shipped beside this file, or (in the repo)
/// the generated copy the pages crate checks.
export function architectTypes() {
  for (const p of [join(here, 'architect.d.ts'), join(here, '../../../pages/types/architect.d.ts')])
    if (existsSync(p)) return readFileSync(p, 'utf8');
  throw new Error('architect.d.ts is missing from @fasttrackstudio/architect-cli');
}

const inside = (path) => typeof path === 'string' && path.length > 0 && !path.startsWith('/') && !path.split(/[\\/]/).includes('..');

/// The manifest in `dir`, read and checked as a typescript extension's:
/// each action's and hook's `script` a `.ts`/`.js` module in the folder.
export function readManifest(dir) {
  const path = join(dir, 'extension.toml');
  if (!existsSync(path)) throw new Error(`no extension.toml in ${dir}`);
  const m = checkManifest(parse(readFileSync(path, 'utf8')));
  if (m.kind !== 'typescript') throw new Error(`the manifest is refused: kind ${JSON.stringify(m.kind)}, this is for kind = "typescript"`);
  const scripts = [
    ...(m.actions ?? []).filter((a) => a.script !== undefined).map((a) => [`actions[${a.id}].script`, a.script]),
    ...(m.hooks ?? []).filter((h) => h.script !== undefined).map((h) => [`hooks[${h.on}].script`, h.script]),
  ];
  for (const a of m.actions ?? [])
    if (a.script === undefined && a.preset === undefined && !(m.windows ?? []).some((w) => w.opens === a.id))
      throw new Error(`the manifest is refused: action ${a.id} has no script and no preset`);
  for (const [field, script] of scripts) {
    if (!inside(script)) throw new Error(`the manifest is refused: ${field} ${JSON.stringify(script)} is outside the package`);
    if (!SCRIPT.test(script)) throw new Error(`the manifest is refused: ${field} ${JSON.stringify(script)}: a typescript extension runs .ts or .js modules`);
    if (!existsSync(join(dir, script))) throw new Error(`${field}: ${script} is not in the folder`);
  }
  for (const v of m.views ?? [])
    if (v.page !== undefined && !existsSync(join(dir, v.page))) throw new Error(`views[${v.id}].page: ${v.page} is not in the folder`);
  return m;
}

/// `types/actions.d.ts`: each action's arguments, by id, as the
/// `"architect"` module's `ActionArgs` (so `defineAction("ID", …)` is
/// typed by the manifest).
export function actionTypes(manifest) {
  const rows = (manifest.actions ?? []).map((a) => {
    const args = a.params ? schemaType(JSON.parse(a.params), 2) : 'null | undefined';
    return `    ${JSON.stringify(a.id)}: ${args};`;
  });
  return `// Generated by \`architect-ext types\` from extension.toml: do not edit.
// Each action's arguments, from its \`params\` schema.
declare module "architect" {
  interface ActionArgs {
${rows.join('\n')}
  }
}
`;
}

/// Writes `<dir>/types/architect.d.ts` and `<dir>/types/actions.d.ts`.
export function writeTypes(dir) {
  const manifest = readManifest(dir);
  const types = join(dir, 'types');
  mkdirSync(types, { recursive: true });
  writeFileSync(join(types, 'architect.d.ts'), architectTypes());
  writeFileSync(join(types, 'actions.d.ts'), actionTypes(manifest));
  return [join(types, 'architect.d.ts'), join(types, 'actions.d.ts')];
}

/// The tsconfig a TypeScript extension type-checks with.
export const TSCONFIG = `${JSON.stringify(
  {
    compilerOptions: {
      target: 'es2022',
      module: 'es2022',
      moduleResolution: 'bundler',
      allowImportingTsExtensions: true,
      noEmit: true,
      strict: true,
      jsx: 'react',
      jsxFactory: 'h',
      jsxFragmentFactory: 'Fragment',
      lib: ['es2022'],
      types: [],
      skipLibCheck: false,
    },
    include: ['actions', 'pages', 'hooks', 'lib', 'types'],
  },
  null,
  2,
)}\n`;

/// `tsc`: the extension's own, else one beside this package.
function tscPath(dir) {
  for (const from of [join(resolve(dir), 'package.json'), join(here, 'package.json')]) {
    try {
      return createRequire(from).resolve('typescript/bin/tsc');
    } catch {
      // next
    }
  }
  throw new Error('no TypeScript to check with: npm install -D typescript');
}

/// Checks the extension in `dir`: its manifest and files, its types
/// written again, then `tsc --noEmit` over it. Throws what is wrong.
export function check(dir) {
  writeTypes(dir);
  if (!existsSync(join(dir, 'tsconfig.json'))) writeFileSync(join(dir, 'tsconfig.json'), TSCONFIG);
  try {
    execFileSync(process.execPath, [tscPath(dir), '--noEmit', '-p', '.'], { cwd: dir, stdio: ['ignore', 'pipe', 'pipe'] });
  } catch (e) {
    const said = `${e.stdout ?? ''}${e.stderr ?? ''}`.trim();
    if (!said) throw e;
    throw new Error(`it does not type-check:\n${said}`);
  }
}

const valid = (id) => /^[a-z0-9._-]+$/.test(id);

/// A new TypeScript extension `id` in `dir`: a manifest, one action that
/// works on save, one page that runs it, its types and a tsconfig.
export function scaffold(id, dir) {
  if (!valid(id)) throw new Error(`id ${JSON.stringify(id)}: lower case letters, digits, . - _`);
  if (existsSync(dir) && readdirSync(dir).length) throw new Error(`${dir} is not empty`);
  const prefix = actionPrefix(id);
  const name = id.split(/[.\-_]/).filter(Boolean).pop() ?? id;
  const title = name[0].toUpperCase() + name.slice(1);
  const files = {
    'extension.toml': `id = ${JSON.stringify(id)}
name = ${JSON.stringify(title)}
version = "0.1.0"
kind = "typescript"
api = "0.1"
description = "A TypeScript extension: actions as .ts files beside a TSX page."

[capabilities]
ui = ["notify"]

[[actions]]
id = "${prefix}HELLO"
name = "${title}: hello"
description = "Says hello to \`name\`."
params = '{"type":"object","properties":{"name":{"type":"string"}},"additionalProperties":false}'
script = "actions/hello.ts"

[[views]]
id = "main"
title = ${JSON.stringify(title)}
page = "pages/main.tsx"
`,
    'actions/hello.ts': `import { defineAction, ui } from "architect";

// Its arguments are the manifest's \`params\` (types/actions.d.ts,
// \`architect-ext types\`); what it returns is the run's answer.
export default defineAction("${prefix}HELLO", async (args, ctx) => {
  const text = \`Hello, \${args?.name ?? "you"}\`;
  await ui.notify(text, "success");
  return { text, from: ctx.source };
});
`,
    'pages/main.tsx': `import { h, useState, actions } from "architect";

export default function Main() {
  const [said, setSaid] = useState("");
  const hello = async () => {
    const out = await actions.run<{ text: string }>("${prefix}HELLO", { name: "${title}" });
    setSaid(out.text);
  };
  return (
    <div style={{ padding: 20, display: "flex", flexDirection: "column", gap: 10 }}>
      <button onClick={hello}>Say hello</button>
      <span>{said}</span>
    </div>
  );
}
`,
    'tsconfig.json': TSCONFIG,
    '.gitignore': 'types/\nnode_modules/\n*.archext\n',
  };
  for (const [path, text] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, path)), { recursive: true });
    writeFileSync(join(dir, path), text);
  }
  writeTypes(dir);
  return Object.keys(files);
}

// ---- the archive ----------------------------------------------------------

/// The package's files, as the archive holds them: everything in `dir`
/// but its types, node_modules, dotfiles and archives; sorted by path.
export function packageFiles(dir) {
  const out = [];
  const walk = (d) => {
    for (const name of readdirSync(d)) {
      if (name.startsWith('.') || name === 'node_modules' || name.endsWith('.archext')) continue;
      const p = join(d, name);
      const rel = relative(dir, p).split('\\').join('/');
      if (rel === 'types' || rel === 'archext.json' || rel === 'archext.json.minisig') continue;
      const st = lstatSync(p);
      if (st.isSymbolicLink()) throw new Error(`${rel}: a link, which an archive does not carry`);
      if (st.isDirectory()) walk(p);
      else out.push([rel, readFileSync(p)]);
    }
  };
  walk(dir);
  return out.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
}

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');

/// `archext.json`'s bytes for `manifest` and `files`.
export function contentIndex(manifest, files) {
  const index = {
    format: 1,
    id: manifest.id,
    version: manifest.version,
    kind: manifest.kind,
    platforms: [],
    files: files.map(([path, bytes]) => ({ path, size: bytes.length, sha256: sha256(bytes) })),
  };
  return Buffer.from(`${JSON.stringify(index, null, 2)}\n`);
}

/// One tar header (ustar): `path` split into prefix and name when long.
function header(path, size) {
  const h = Buffer.alloc(512);
  let name = path;
  let prefix = '';
  if (Buffer.byteLength(path) > 100) {
    const at = path.lastIndexOf('/', 155);
    if (at < 0 || Buffer.byteLength(path.slice(at + 1)) > 100) throw new Error(`${path}: too long a path for the archive`);
    prefix = path.slice(0, at);
    name = path.slice(at + 1);
  }
  const put = (text, at, len) => h.write(text, at, len, 'utf8');
  const octal = (n, len) => n.toString(8).padStart(len - 1, '0') + '\0';
  put(name, 0, 100);
  put(octal(0o644, 8), 100, 8);
  put(octal(0, 8), 108, 8);
  put(octal(0, 8), 116, 8);
  put(octal(size, 12), 124, 12);
  put(octal(0, 12), 136, 12);
  h.fill(' ', 148, 156);
  put('0', 156, 1);
  put('ustar\0', 257, 6);
  put('00', 263, 2);
  put(prefix, 345, 155);
  let sum = 0;
  for (const b of h) sum += b;
  put(`${sum.toString(8).padStart(6, '0')}\0 `, 148, 8);
  return h;
}

/// A gzipped tar of `entries` (`[path, bytes]`), in order.
export function tarGz(entries) {
  const parts = [];
  for (const [path, bytes] of entries) {
    parts.push(header(path, bytes.length), bytes);
    const pad = (512 - (bytes.length % 512)) % 512;
    if (pad) parts.push(Buffer.alloc(pad));
  }
  parts.push(Buffer.alloc(1024));
  return gzipSync(Buffer.concat(parts), { level: 9 });
}

// ---- minisign (sign::SecretKey's format) ------------------------------------

const blake2b512 = (bytes) => createHash('blake2b512').update(bytes).digest();

/// An Ed25519 private key from its 32-byte seed.
const privateKey = (seed) =>
  createPrivateKey({ key: Buffer.concat([Buffer.from('302e020100300506032b657004220420', 'hex'), seed]), format: 'der', type: 'pkcs8' });

/// A minisign secret key file's text, unencrypted (`minisign -G -W`, as
/// `cargo xtask ext-keygen` writes): its key id and Ed25519 seed.
export function readSecretKey(text) {
  const line = text.split(/\r?\n/).map((l) => l.trim()).find((l) => l && !l.startsWith('untrusted comment:'));
  if (!line) throw new Error('the key file is empty');
  const raw = Buffer.from(line, 'base64');
  if (raw.length !== 158) throw new Error('not a minisign secret key (wrong length)');
  if (raw.subarray(0, 2).toString() !== 'Ed' || raw.subarray(4, 6).toString() !== 'B2') throw new Error('not a minisign Ed25519 secret key');
  if (raw[2] !== 0 || raw[3] !== 0) throw new Error('the key is encrypted (a password): give an unencrypted one, as `minisign -G -W` writes');
  const keynum = raw.subarray(54, 62);
  const seed = raw.subarray(62, 94);
  const pub = createPublicKey(privateKey(seed)).export({ format: 'der', type: 'spki' }).subarray(-32);
  if (!pub.equals(raw.subarray(94, 126))) throw new Error('its public half does not match its secret half');
  return { keynum, seed };
}

/// A minisign signature file over `message` with `trusted` as its trusted
/// comment (`sign::SecretKey::sign`).
export function minisign(message, key, trusted) {
  const sk = privateKey(key.seed);
  const sig = edSign(null, blake2b512(message), sk);
  const global = edSign(null, Buffer.concat([sig, Buffer.from(trusted)]), sk);
  return `untrusted comment: signature from architect-ext pack\n${Buffer.concat([Buffer.from('ED'), key.keynum, sig]).toString('base64')}\ntrusted comment: ${trusted}\n${global.toString('base64')}\n`;
}

/// A throwaway key pair for trials and tests (never a release key):
/// `{ secret, public }`, each a minisign file's text.
export function keygen() {
  const keynum = randomBytes(8);
  const seed = randomBytes(32);
  const pub = createPublicKey(privateKey(seed)).export({ format: 'der', type: 'spki' }).subarray(-32);
  const sk = Buffer.concat([seed, pub]);
  // Its checksum (BLAKE2b-256) left zero, which a reader accepts.
  const raw = Buffer.concat([Buffer.from('Ed'), Buffer.alloc(2), Buffer.from('B2'), Buffer.alloc(48), keynum, sk, Buffer.alloc(32)]);
  const id = Buffer.from(keynum).reverse().toString('hex').toUpperCase();
  return {
    secret: `untrusted comment: minisign encrypted secret key\n${raw.toString('base64')}\n`,
    public: `untrusted comment: minisign public key ${id}\n${Buffer.concat([Buffer.from('Ed'), keynum, pub]).toString('base64')}\n`,
  };
}

/// The `.archext` of the TypeScript extension in `dir`, signed with `key`
/// (a minisign secret key file's text) when one is given: `{ bytes,
/// index }`. Checked first (`readManifest`).
export function pack(dir, key) {
  const manifest = readManifest(dir);
  const files = packageFiles(dir);
  const index = contentIndex(manifest, files);
  const entries = [['archext.json', index]];
  if (key) {
    const trusted = `archext ${manifest.id} ${manifest.version}`;
    entries.push(['archext.json.minisig', Buffer.from(minisign(index, readSecretKey(key), trusted))]);
  }
  entries.push(...files);
  return { bytes: tarGz(entries), index: JSON.parse(index.toString()) };
}
