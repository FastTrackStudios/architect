//! The generated guide: `<app dir>/AGENTS.md` and `actions.schema.json`,
//! written from the app's live Action List (#268 H2).
//!
//! herdr writes `AGENTS.md` into its home folder on every start, and a
//! test fails when the guide misses a command. Here the guide is the
//! app's own [`Guide::preamble`] (a hand-written template; architect's
//! default when the app has none) followed by every action the CLI's
//! caller may run, grouped by the id's area (`WORKSPACE_`, `THEME_`): its
//! effect, its arguments (name, type, whether required) and what it does.
//! Beside it, `actions.schema.json` is what `actions schema` prints.
//!
//! An app's actions come and go while it runs (a page's, an extension's),
//! so [`Guide::keep_written`] writes both once the app has settled and
//! again whenever an action joins or leaves the list.
//!
//! The template's placeholders: `{{app}}` (its name), `{{dir}}` (this
//! folder), `{{actions}}` (the command that reaches the running app:
//! `architect-desktop actions`), `{{escape}}` (the escape-hatch chord).

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::sync::Arc;
use std::sync::atomic::{AtomicBool, Ordering};
use std::time::{Duration, Instant};

use architect::action::{ActionInfo, EventKind};
use serde_json::Value;

use crate::Surface;
use crate::protocol::effect_name;

/// The guide's file name.
pub const GUIDE_FILE: &str = "AGENTS.md";

/// The schema's file name.
pub const SCHEMA_FILE: &str = "actions.schema.json";

/// architect's preamble, for an app that has none of its own.
pub const DEFAULT_PREAMBLE: &str = include_str!("guide_preamble.md");

/// The escape hatch's chord, as the guide names it.
pub const ESCAPE_CHORD: &str = "Ctrl+Alt+Shift+Escape (Cmd+Alt+Shift+Escape on macOS)";

/// The line every generated file starts with.
#[must_use]
pub fn header(app: &str) -> String {
    format!(
        "<!-- Generated by {app} on every start from its live Action List. Edits here are overwritten. -->"
    )
}

/// How an app's guide is made.
#[derive(Clone, Debug)]
pub struct Guide {
    app: String,
    actions: String,
    preamble: String,
}

/// What [`Guide::write`] wrote.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Written {
    pub guide: PathBuf,
    pub schema: PathBuf,
    /// The guide's size, bytes.
    pub bytes: usize,
    /// How many actions it names.
    pub actions: usize,
}

impl Guide {
    /// The guide of app `app`, reached as `<app> actions` with
    /// architect's preamble.
    #[must_use]
    pub fn new(app: impl Into<String>) -> Self {
        let app = app.into();
        Self {
            actions: format!("{app} actions"),
            app,
            preamble: DEFAULT_PREAMBLE.to_owned(),
        }
    }

    /// The command that reaches the running app (`task actions`).
    #[must_use]
    pub fn command(mut self, actions: impl Into<String>) -> Self {
        self.actions = actions.into();
        self
    }

    /// The app's own preamble: a template with the placeholders the
    /// module names.
    #[must_use]
    pub fn preamble(mut self, template: impl Into<String>) -> Self {
        self.preamble = template.into();
        self
    }

    /// The guide for `surface` (its caller's actions), as the folder
    /// `dir` holds it.
    #[must_use]
    pub fn render(&self, surface: &Surface, dir: &Path) -> String {
        let infos = surface.list().infos_for(surface.principal());
        let mut out = header(&self.app);
        out.push_str("\n\n");
        out.push_str(
            &self
                .preamble
                .replace("{{app}}", &self.app)
                .replace("{{dir}}", &dir.display().to_string())
                .replace("{{actions}}", &self.actions)
                .replace("{{escape}}", ESCAPE_CHORD),
        );
        if !out.ends_with('\n') {
            out.push('\n');
        }
        out.push_str(&reference(&infos, &self.actions));
        out
    }

    /// Writes the guide and the schema into `dir` (made when missing),
    /// each whole or not at all.
    ///
    /// # Errors
    ///
    /// The folder or a file could not be written.
    pub fn write(&self, surface: &Surface, dir: &Path) -> std::io::Result<Written> {
        std::fs::create_dir_all(dir)?;
        let guide = self.render(surface, dir);
        let schema = serde_json::to_string_pretty(&surface.schema(surface.principal()))
            .map_err(std::io::Error::other)?;
        let guide_path = dir.join(GUIDE_FILE);
        let schema_path = dir.join(SCHEMA_FILE);
        replace(&guide_path, guide.as_bytes())?;
        replace(&schema_path, schema.as_bytes())?;
        Ok(Written {
            guide: guide_path,
            schema: schema_path,
            bytes: guide.len(),
            actions: surface.list().infos_for(surface.principal()).len(),
        })
    }

    /// Writes the guide into `dir` once the app has settled (`settle`
    /// with no action joining or leaving), then again each time one does,
    /// on a thread of its own, until the [`KeptWritten`] is dropped.
    #[must_use]
    pub fn keep_written(self, surface: Surface, dir: PathBuf, settle: Duration) -> KeptWritten {
        let stop = Arc::new(AtomicBool::new(false));
        let stopped = Arc::clone(&stop);
        let spawned = std::thread::Builder::new()
            .name("agents-guide".to_owned())
            .spawn(move || {
                let list = surface.list().clone();
                let mut since = list.latest();
                let mut due = Some(Instant::now() + settle);
                while !stopped.load(Ordering::Relaxed) {
                    let wait = due.map_or(Duration::from_millis(500), |at| {
                        at.saturating_duration_since(Instant::now())
                            .min(Duration::from_millis(500))
                    });
                    let (events, next) = list.events_since(since, 256, wait);
                    since = next;
                    let moved = events.iter().any(|e| {
                        matches!(
                            e.kind,
                            EventKind::Registered { .. } | EventKind::Unregistered { .. }
                        )
                    });
                    if moved {
                        // Wait for the rest of a burst (a page mounting).
                        due = Some(Instant::now() + Duration::from_millis(300));
                    }
                    if due.is_some_and(|at| Instant::now() >= at) {
                        due = None;
                        if let Err(error) = self.write(&surface, &dir) {
                            tracing::warn!(%error, dir = %dir.display(), "the agents' guide was not written");
                        }
                    }
                }
            });
        if let Err(error) = spawned {
            tracing::warn!(%error, "the agents' guide has no thread to write it");
        }
        KeptWritten { stop }
    }
}

/// The guide being kept written; dropping it stops that.
#[derive(Debug)]
pub struct KeptWritten {
    stop: Arc<AtomicBool>,
}

impl Drop for KeptWritten {
    fn drop(&mut self) {
        self.stop.store(true, Ordering::Relaxed);
    }
}

/// Writes `bytes` to `path` through a sibling file renamed over it.
fn replace(path: &Path, bytes: &[u8]) -> std::io::Result<()> {
    if std::fs::read(path).is_ok_and(|now| now == bytes) {
        return Ok(());
    }
    let name = path
        .file_name()
        .map_or_else(|| "guide".into(), |n| n.to_string_lossy().into_owned());
    let temporary = path.with_file_name(format!(".{name}.{}.tmp", std::process::id()));
    std::fs::write(&temporary, bytes)?;
    std::fs::rename(&temporary, path).inspect_err(|_| {
        let _ = std::fs::remove_file(&temporary);
    })
}

/// The id's area: everything before its first `_` (`WORKSPACES`).
fn area(id: &str) -> &str {
    id.split_once('_').map_or(id, |(a, _)| a)
}

/// Every action, by area: its id, effect, arguments and what it does.
#[must_use]
pub fn reference(infos: &[ActionInfo], actions: &str) -> String {
    let mut areas: BTreeMap<&str, Vec<&ActionInfo>> = BTreeMap::new();
    for info in infos {
        areas.entry(area(&info.id)).or_default().push(info);
    }
    let mut out = String::new();
    let _ = writeln!(
        out,
        "\n## Every action\n\n{} actions, by area. Each says its effect (read-only, mutating, \
         destructive), the arguments it takes (`name: type`, by name; `?` when it may be left out) and \
         what it does. `{actions} describe ID` or `actions.schema.json` beside this file has \
         each one's full schema.",
        infos.len()
    );
    for (area, infos) in areas {
        let _ = writeln!(out, "\n### {area}\n");
        for info in infos {
            let _ = write!(out, "- `{}` ({})", info.id, effect_name(info.effect));
            let args = arguments(info.params_schema.as_deref());
            if !args.is_empty() {
                let _ = write!(out, " `{{{args}}}`");
            }
            let what = if info.description.is_empty() {
                &info.display_name
            } else {
                &info.description
            };
            let _ = write!(out, ": {}", one_line(what));
            if !info.shortcut.is_empty() {
                let _ = write!(out, " Key: {}.", info.shortcut);
            }
            if let Some(why) = &info.disabled_reason {
                let _ = write!(out, " (Disabled now: {}.)", one_line(why));
            }
            out.push('\n');
        }
    }
    out
}

/// A description on one line.
fn one_line(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// `name: type, other?: type` from a params schema.
fn arguments(schema: Option<&str>) -> String {
    let Some(schema) = schema.and_then(|s| serde_json::from_str::<Value>(s).ok()) else {
        return String::new();
    };
    let required: Vec<&str> = schema
        .get("required")
        .and_then(Value::as_array)
        .map(|r| r.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let Some(properties) = schema.get("properties").and_then(Value::as_object) else {
        return String::new();
    };
    properties
        .iter()
        .map(|(name, prop)| {
            let optional = if required.contains(&name.as_str()) {
                ""
            } else {
                "?"
            };
            format!("{name}{optional}: {}", type_of(prop))
        })
        .collect::<Vec<_>>()
        .join(", ")
}

/// A property's type, short: `string`, `integer`, `"a" | "b"`, `object`.
fn type_of(prop: &Value) -> String {
    if let Some(choices) = prop.get("enum").and_then(Value::as_array) {
        return choices
            .iter()
            .map(|c| c.to_string())
            .collect::<Vec<_>>()
            .join(" | ");
    }
    match prop.get("type") {
        Some(Value::String(t)) if t == "array" => {
            let item = prop.get("items").map_or_else(|| "any".to_owned(), type_of);
            format!("{item}[]")
        }
        Some(Value::String(t)) => t.clone(),
        Some(Value::Array(ts)) => ts
            .iter()
            .filter_map(Value::as_str)
            .collect::<Vec<_>>()
            .join(" | "),
        _ => ["anyOf", "oneOf", "allOf"]
            .iter()
            .find_map(|k| prop.get(*k).and_then(Value::as_array))
            .map_or_else(
                || "any".to_owned(),
                |options| {
                    options
                        .iter()
                        .map(type_of)
                        .filter(|t| t != "null")
                        .collect::<Vec<_>>()
                        .join(" | ")
                },
            ),
    }
}

#[cfg(test)]
mod tests {
    use architect::action::{ActionList, ActionMeta, Effect};
    use facet::Facet;

    use super::{GUIDE_FILE, Guide, SCHEMA_FILE, header};
    use crate::Surface;

    static OPEN: ActionMeta = ActionMeta {
        id: "PANE_OPEN",
        trait_name: "",
        method_name: "",
        display_name: "Open",
        description: "Opens a pane\n   where asked.",
        category: "Panes",
        group: "Panes",
        shortcut: "",
        toggleable: false,
        undo: false,
    };
    static WIPE: ActionMeta = ActionMeta {
        id: "DISK_WIPE",
        description: "",
        display_name: "Wipe the disk",
        ..OPEN
    };

    #[derive(Facet)]
    struct Open {
        /// Which.
        view: String,
        at: Option<u32>,
    }

    /// The guide names every action with its effect and arguments, under
    /// the generated header, its placeholders filled; the schema is
    /// written beside it.
    #[test]
    fn the_guide_names_every_action() {
        let list = ActionList::new();
        list.register(&OPEN, Effect::Mutating, |_: Open| Ok::<_, String>(()))
            .unwrap();
        list.register(&WIPE, Effect::Destructive, |(): ()| Ok::<_, String>(()))
            .unwrap();
        let surface = Surface::new("demo", "1", list.clone());
        let dir = std::env::temp_dir().join(format!("guide-{}", std::process::id()));
        let guide = Guide::new("demo")
            .preamble("# {{app}} in {{dir}}\nRun `{{actions}} list`. {{escape}}.\n");
        let written = guide.write(&surface, &dir).unwrap();
        let text = std::fs::read_to_string(dir.join(GUIDE_FILE)).unwrap();
        assert!(text.starts_with(&header("demo")), "{text}");
        assert!(
            text.contains(&format!("# demo in {}", dir.display())),
            "{text}"
        );
        assert!(text.contains("Run `demo actions list`"), "{text}");
        assert!(text.contains("Ctrl+Alt+Shift+Escape"), "{text}");
        assert!(
            text.contains(
                "- `PANE_OPEN` (mutating) `{at?: integer, view: string}`: Opens a pane where asked."
            ),
            "{text}"
        );
        assert!(
            text.contains("- `DISK_WIPE` (destructive): Wipe the disk"),
            "{text}"
        );
        assert!(
            text.contains("### DISK") && text.contains("### PANE"),
            "{text}"
        );
        for info in list.infos() {
            assert!(
                text.contains(&format!("`{}`", info.id)),
                "{} is missing",
                info.id
            );
        }
        assert_eq!(written.actions, 2);
        let schema: serde_json::Value =
            serde_json::from_str(&std::fs::read_to_string(dir.join(SCHEMA_FILE)).unwrap()).unwrap();
        assert_eq!(schema["oneOf"].as_array().map(Vec::len), Some(2));
        let _ = std::fs::remove_dir_all(&dir);
    }
}
