//! The page API's types, for the files a page is written in (feature
//! `codegen`).
//!
//! `architect.d.ts` for TSX/JS pages and `architect.d.luau` for Luau
//! ones, both from the vox descriptors of [`crate::api`]'s services, so
//! the types a page is checked against are the API's own.
//!
//! - [`typescript`]: the named types and each service's caller interface
//!   from `vox_codegen::targets::typescript` (as Task's
//!   `task:xtask/src/main.rs` `codegen_typescript` does), inside
//!   `declare module "architect"`, then the runtime's own surface (`h`,
//!   hooks, `actions`, `theme`, `worker`…) and the JSX namespace.
//! - [`luau`]: the same named types as Luau type aliases, and the Luau
//!   element builder's surface.
//!
//! [`write_types`] writes both into an app's folder; the app calls it at
//! start (the seam the generated guide of #270 calls). The copies checked
//! in under `features/pages/types/` are compared with what this makes by
//! a test, so they never drift.

