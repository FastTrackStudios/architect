/// The page API's services: the host's and the view's, each with its
/// stream sibling (its `#[subscribe]` streams).
#[must_use]
pub fn descriptors() -> Vec<&'static ServiceDescriptor> {
    vec![
        host::page_host_service_descriptor(),
        host::page_host_stream_service_descriptor(),
        view::page_view_service_descriptor(),
        view::page_view_stream_service_descriptor(),
    ]
}

/// Every named type the services reach, once each, in order.
fn named_types() -> Vec<(String, &'static Shape)> {
    let mut out: Vec<(String, &'static Shape)> = Vec::new();
    for service in descriptors() {
        for (name, shape) in collect_named_types(service) {
            if !out.iter().any(|(n, _)| *n == name) {
                out.push((name, shape));
            }
        }
    }
    out
}

const HEADER: &str = "\
// @generated by architect-pages (features/pages/src/codegen.rs) from the
// page API's vox descriptors (features/pages/src/api.rs). Do not edit: the
// app writes it into its folder at every start.
";

/// `architect.d.ts`.
#[must_use]
pub fn typescript() -> String {
    let mut out = String::from(HEADER);
    out.push_str("\ndeclare module \"architect\" {\n");
    let mut body = String::new();
    body.push_str(&generate_named_types(&named_types()));
    for service in descriptors() {
        body.push_str(&generate_caller_interface(service));
    }
    body.push_str(TS_RUNTIME);
    for line in body.lines() {
        if line.is_empty() {
            out.push('\n');
        } else {
            let _ = writeln!(out, "  {line}");
        }
    }
    out.push_str("}\n");
    out.push_str(TS_GLOBALS);
    out
}

/// `architect.d.luau`.
#[must_use]
pub fn luau() -> String {
    let mut out = HEADER.replace("//", "--");
    out.push_str("\n-- The page API's types.\n\n");
    for (name, shape) in named_types() {
        if let ShapeKind::Struct(info) = classify_shape(shape) {
            let _ = writeln!(out, "export type {name} = {{");
            for f in info.fields {
                let _ = writeln!(out, "\t{}: {},", f.name, luau_type(f.shape()));
            }
            out.push_str("}\n\n");
        }
    }
    out.push_str(LUAU_RUNTIME);
    out
}

fn luau_type(shape: &'static Shape) -> String {
    match classify_shape(shape) {
        ShapeKind::Scalar(ScalarType::Bool) => "boolean".to_owned(),
        ShapeKind::Scalar(
            ScalarType::String | ScalarType::Str | ScalarType::CowStr | ScalarType::Char,
        ) => "string".to_owned(),
        ShapeKind::Scalar(ScalarType::Unit) => "nil".to_owned(),
        ShapeKind::Scalar(_) => "number".to_owned(),
        ShapeKind::Option { inner } => format!("{}?", luau_type(inner)),
        ShapeKind::List { element }
        | ShapeKind::Slice { element }
        | ShapeKind::Array { element, .. }
        | ShapeKind::Set { element } => format!("{{ {} }}", luau_type(element)),
        ShapeKind::Map { key, value } => {
            format!("{{ [{}]: {} }}", luau_type(key), luau_type(value))
        }
        ShapeKind::Struct(info) => info
            .name
            .map_or_else(|| "{ [string]: any }".to_owned(), str::to_owned),
        _ => "any".to_owned(),
    }
}

/// Writes `architect.d.ts` and `architect.d.luau` into `dir` (an app's
/// folder), each only when it differs; the paths written to.
///
/// # Errors
///
/// A file could not be written.
pub fn write_types(dir: &Path) -> std::io::Result<Vec<PathBuf>> {
    std::fs::create_dir_all(dir)?;
    let mut out = Vec::new();
    for (name, text) in [(DTS, typescript()), (LUAU, luau())] {
        let path = dir.join(name);
        if std::fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
            std::fs::write(&path, text)?;
        }
        out.push(path);
    }
    Ok(out)
}

