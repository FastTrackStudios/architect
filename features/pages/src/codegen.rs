//! The page API's types, for the files a page is written in (feature
//! `codegen`).
//!
//! `architect.d.ts` for TSX/JS pages and `architect.d.luau` for Luau
//! ones, both from the vox descriptors of [`crate::api`]'s services, so
//! the types a page is checked against are the API's own.
//!
//! - [`typescript`]: the named types and each service's caller interface
//!   from `vox_codegen::targets::typescript` (as Task's
//!   `task:xtask/src/main.rs` `codegen_typescript` does), inside
//!   `declare module "architect"`, then the runtime's own surface (`h`,
//!   hooks, `actions`, `theme`, `worker`…) and the JSX namespace.
//! - [`luau`]: the same named types as Luau type aliases, and the Luau
//!   element builder's surface.
//!
//! [`write_types`] writes both into an app's folder; the app calls it at
//! start (the seam the generated guide of #270 calls). The copies checked
//! in under `features/pages/types/` are compared with what this makes by
//! a test, so they never drift.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use facet::{ScalarType, Shape};
use vox_codegen::targets::typescript::client::generate_caller_interface;
use vox_codegen::targets::typescript::types::{collect_named_types, generate_named_types};
use vox_types::{ServiceDescriptor, ShapeKind, classify_shape};

use crate::api::{host, view};

/// The TypeScript declarations' file name.
pub const DTS: &str = "architect.d.ts";

/// The Luau type definitions' file name.
pub const LUAU: &str = "architect.d.luau";

/// The page API's services: the host's and the view's, each with its
/// stream sibling (its `#[subscribe]` streams).
#[must_use]
pub fn descriptors() -> Vec<&'static ServiceDescriptor> {
    vec![
        host::page_host_service_descriptor(),
        host::page_host_stream_service_descriptor(),
        view::page_view_service_descriptor(),
        view::page_view_stream_service_descriptor(),
    ]
}

/// Every named type the services reach, once each, in order.
fn named_types() -> Vec<(String, &'static Shape)> {
    let mut out: Vec<(String, &'static Shape)> = Vec::new();
    for service in descriptors() {
        for (name, shape) in collect_named_types(service) {
            if !out.iter().any(|(n, _)| *n == name) {
                out.push((name, shape));
            }
        }
    }
    out
}

const HEADER: &str = "\
// @generated by architect-pages (features/pages/src/codegen.rs) from the
// page API's vox descriptors (features/pages/src/api.rs). Do not edit: the
// app writes it into its folder at every start.
";

/// `architect.d.ts`.
#[must_use]
pub fn typescript() -> String {
    let mut out = String::from(HEADER);
    out.push_str("\ndeclare module \"architect\" {\n");
    let mut body = String::new();
    body.push_str(&generate_named_types(&named_types()));
    for service in descriptors() {
        body.push_str(&generate_caller_interface(service));
    }
    body.push_str(TS_RUNTIME);
    for line in body.lines() {
        if line.is_empty() {
            out.push('\n');
        } else {
            let _ = writeln!(out, "  {line}");
        }
    }
    out.push_str("}\n");
    out.push_str(TS_GLOBALS);
    out
}

/// `architect.d.luau`.
#[must_use]
pub fn luau() -> String {
    let mut out = HEADER.replace("//", "--");
    out.push_str("\n-- The page API's types.\n\n");
    for (name, shape) in named_types() {
        if let ShapeKind::Struct(info) = classify_shape(shape) {
            let _ = writeln!(out, "export type {name} = {{");
            for f in info.fields {
                let _ = writeln!(out, "\t{}: {},", f.name, luau_type(f.shape()));
            }
            out.push_str("}\n\n");
        }
    }
    out.push_str(LUAU_RUNTIME);
    out
}

fn luau_type(shape: &'static Shape) -> String {
    match classify_shape(shape) {
        ShapeKind::Scalar(ScalarType::Bool) => "boolean".to_owned(),
        ShapeKind::Scalar(
            ScalarType::String | ScalarType::Str | ScalarType::CowStr | ScalarType::Char,
        ) => "string".to_owned(),
        ShapeKind::Scalar(ScalarType::Unit) => "nil".to_owned(),
        ShapeKind::Scalar(_) => "number".to_owned(),
        ShapeKind::Option { inner } => format!("{}?", luau_type(inner)),
        ShapeKind::List { element }
        | ShapeKind::Slice { element }
        | ShapeKind::Array { element, .. }
        | ShapeKind::Set { element } => format!("{{ {} }}", luau_type(element)),
        ShapeKind::Map { key, value } => {
            format!("{{ [{}]: {} }}", luau_type(key), luau_type(value))
        }
        ShapeKind::Struct(info) => info
            .name
            .map_or_else(|| "{ [string]: any }".to_owned(), str::to_owned),
        _ => "any".to_owned(),
    }
}

/// Writes `architect.d.ts` and `architect.d.luau` into `dir` (an app's
/// folder), each only when it differs; the paths written to.
///
/// # Errors
///
/// A file could not be written.
pub fn write_types(dir: &Path) -> std::io::Result<Vec<PathBuf>> {
    std::fs::create_dir_all(dir)?;
    let mut out = Vec::new();
    for (name, text) in [(DTS, typescript()), (LUAU, luau())] {
        let path = dir.join(name);
        if std::fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
            std::fs::write(&path, text)?;
        }
        out.push(path);
    }
    Ok(out)
}

/// The JS runtime's own surface (`crate::js`'s prelude), inside the
/// module: what a page imports from `"architect"`.
const TS_RUNTIME: &str = r#"
// ── The runtime: what a page imports ─────────────────────────────────

/** What `h` (and JSX) makes: one node of the tree a page renders. */
export type Node = Element;

/** What a component may return, and what goes between tags. */
export type Child = Node | string | number | boolean | null | undefined | Child[];

/**
 * A style: CSS text, or an object of properties (`camelCase` or
 * `kebab-case`; a number is pixels, except unitless ones). A value
 * `"$foreground"` is the theme's token, `var(--foreground)`: write
 * colours through the theme so the page follows it live.
 */
export type Style = string | { [property: string]: string | number | null | undefined };

/** What an element takes: its attributes, `key`, `style`, handlers. */
export interface Props {
  key?: string | number;
  class?: string;
  style?: Style;
  children?: Child;
  onClick?: (event: PageEvent) => void;
  onDblClick?: (event: PageEvent) => void;
  onContextMenu?: (event: PageEvent) => void;
  onMouseDown?: (event: PageEvent) => void;
  onMouseUp?: (event: PageEvent) => void;
  onInput?: (event: PageEvent) => void;
  onChange?: (event: PageEvent) => void;
  onKeyDown?: (event: PageEvent) => void;
  onKeyUp?: (event: PageEvent) => void;
  onFocus?: (event: PageEvent) => void;
  onBlur?: (event: PageEvent) => void;
  [attribute: string]: unknown;
}

/** A function component. */
export type Component<P = {}> = (props: P & { children?: Child }) => Child;

/** JSX's factory (`jsxFactory: "h"`); oxc compiles `<div/>` to it. */
export function h(tag: string | Component<any>, props?: Props | null, ...children: Child[]): Node;
/** `<>…</>`. */
export function Fragment(props: { children?: Child }): Child;

/** A value kept across renders; setting it renders again. */
export function useState<T>(initial: T | (() => T)): [T, (next: T | ((prev: T) => T)) => void];
/** A box kept across renders; setting it does not render. */
export function useRef<T>(initial: T): { current: T };
/** Runs `effect` after a render when `deps` changed (each render with none); its return runs before the next and on unmount. */
export function useEffect(effect: () => void | (() => void), deps?: unknown[]): void;
/** Live data: runs action `id` with `args` now and every `every` ms (and on `refresh()`), rendering again with each answer. */
export function useData<T = unknown>(id: string, args?: unknown, options?: { every?: number }): {
  value: T | undefined;
  error: string | undefined;
  loading: boolean;
  refresh(): void;
};
/** A shared-state key every page of the app sees; setting it renders each that reads it. */
export function useShared<T>(key: string, initial: T): [T, (value: T) => void];
/** An inline embed's input — the claim (`fence:kf`), the block's text, the host's properties — or undefined in a pane; the page renders again when the block changes. */
export function useEmbed(): Embed | undefined;
/** The theme now; the page renders again when it changes. */
export function useTheme(): Theme;
/** Asks for a render (after work a handler did not await). */
export function invalidate(): void;

/** What a host gives an inline embed. */
export interface Embed {
  readonly claim: string;
  readonly source: string;
  readonly props: unknown;
}

/** The theme showing: a snapshot, made again only when `revision` moves. */
export interface Theme {
  readonly id: string;
  readonly scheme: "light" | "dark";
  readonly revision: number;
  /** Every resolved token, by name. */
  readonly tokens: { readonly [name: string]: string };
  /** A token's CSS value (`#1f2937`), or `undefined`. */
  value(name: string): string | undefined;
  /** `var(--name)`: what to write in a style, so it follows the theme. */
  css(name: string): string;
}
export const theme: Theme;

/** The Action List: what the page's extension may run. */
export const actions: {
  run<T = unknown>(id: string, args?: unknown): Promise<T>;
  list(filter?: string): Promise<ActionSummary[]>;
};
/** The app's settings. */
export const settings: {
  get<T = unknown>(key: string): Promise<T | null>;
  set(key: string, value: unknown): Promise<void>;
};
/** State shared by every page of the app. */
export const state: {
  get<T = unknown>(key: string): T | undefined;
  set(key: string, value: unknown): void;
  /** `fn` on each change of `key`; the return stops it. */
  watch(key: string, fn: (value: unknown) => void): () => void;
};
/** Shows a notification. */
export function notify(text: string, kind?: "info" | "success" | "warning" | "error"): void;

/** A worker: a script of the page's folder in a runtime of its own, spoken to by messages. */
export interface Worker {
  readonly id: number;
  post(message: unknown): void;
  onMessage(fn: (message: unknown) => void): void;
  onDone(fn: (result: unknown, error: string | undefined) => void): void;
  /** Stops it (a Luau worker's `w:cancel()`). */
  cancel(): void;
  /** `cancel`, as a Web Worker says it. */
  terminate(): void;
}
export const worker: {
  /** Starts `file` (in the page's folder: `"job.js"`) with `args`. */
  spawn(file: string, args?: unknown): Worker;
};

/** A dialog or popup over the page. */
export function Overlay(props: {
  kind?: "dialog" | "popup";
  title?: string;
  onClose?: () => void;
  children?: Child;
}): Node;

/** The raw host service, as vox describes it. */
export const host: PageHostCaller;
"#;

/// Outside the module: JSX's namespace, a worker's module, the globals.
const TS_GLOBALS: &str = r#"
/** What a worker script (`worker.spawn("job.js")`) imports. */
declare module "architect/worker" {
  /** What `spawn` gave it. */
  export const args: unknown;
  /** A message to the page. */
  export function post(message: unknown): void;
  /** `fn` for each message from the page. */
  export function onMessage(fn: (message: unknown) => void): void;
}

declare namespace JSX {
  type Element = import("architect").Node;
  interface IntrinsicElements {
    [tag: string]: import("architect").Props;
  }
  interface ElementChildrenAttribute {
    children: {};
  }
}

/** Lines in the extension's log. No Node APIs: `fetch` and files only through actions the page's capabilities reach. */
declare const console: {
  log(...values: unknown[]): void;
  info(...values: unknown[]): void;
  warn(...values: unknown[]): void;
  error(...values: unknown[]): void;
};
declare function setTimeout(fn: () => void, ms?: number): number;
declare function clearTimeout(id: number): void;
declare function setInterval(fn: () => void, ms: number): number;
declare function clearInterval(id: number): void;
"#;

/// The Luau element builder's surface (`crate::luau`).
const LUAU_RUNTIME: &str = r#"
-- ── The element builder: what a Luau page has ─────────────────────────

-- One element under construction: each method returns it, to chain.
export type Builder = {
	child: (self: Builder, child: Builder | string | number) -> Builder,
	children: (self: Builder, children: { Builder | string | number }) -> Builder,
	key: (self: Builder, key: string | number) -> Builder,
	attr: (self: Builder, name: string, value: string | number | boolean) -> Builder,
	class: (self: Builder, class: string) -> Builder,
	-- CSS text, or a table of properties; `$foreground` is `var(--foreground)`.
	style: (self: Builder, style: string | { [string]: string | number }) -> Builder,
	on: (self: Builder, event: string, fn: (event: PageEvent) -> ()) -> Builder,
	on_click: (self: Builder, fn: (event: PageEvent) -> ()) -> Builder,
	on_input: (self: Builder, fn: (event: PageEvent) -> ()) -> Builder,
	on_key_down: (self: Builder, fn: (event: PageEvent) -> ()) -> Builder,
}

-- Globals of a Luau page:
--   div(), span(), button(), input(), h1() … h3(), p(), ul(), li(), el(tag): a Builder
--   text(s): a text node
--   render(fn): `fn()` returns the page's Builder; called for every frame
--   invalidate(): asks for a frame
--   actions.run(id, args?), state.query(id, args?): as every script
--   theme.value(name), theme.scheme, theme.revision: the app's theme
--   embed(): an inline embed's input ({ claim, source, props }), nil in a pane
--   set_timeout(fn, ms), set_interval(fn, ms): a timer's id; clear_timeout(id), clear_interval(id)
--   worker.spawn(file, args?): a Worker running `file`, a `.luau` of the page's folder

-- How far a worker said it is.
export type WorkerProgress = { done: number, total: number?, fraction: number?, note: string? }

-- A worker: a script of the page's folder in a Luau state of its own, spoken to by messages.
export type Worker = {
	id: number,
	name: string,
	post: (self: Worker, message: any) -> (),
	cancel: (self: Worker) -> (),
	status: (self: Worker) -> "running" | "done" | "failed" | "cancelled",
	progress: (self: Worker) -> WorkerProgress?,
	result: (self: Worker) -> (any, string?),
	on_message: (self: Worker, fn: (message: any) -> ()) -> (),
	on_progress: (self: Worker, fn: (progress: WorkerProgress) -> ()) -> (),
	on_done: (self: Worker, fn: (result: any, error: string?) -> ()) -> (),
}
"#;
