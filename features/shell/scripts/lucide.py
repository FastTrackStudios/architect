#!/usr/bin/env python3
"""Writes features/shell/src/lucide/lucide_data.rs: every Lucide icon as data.

Each icon of lucide-dioxus (the workspace's pinned tag) is a component
of its own, with props of its own; this reads their SVG children (path,
circle, polyline, polygon) so one component draws any icon by name
(`architect_shell::lucide`).

    python3 features/shell/scripts/lucide.py \\
        ~/.cargo/git/checkouts/lucide-*/<rev>/packages/dioxus/src \\
        > features/shell/src/lucide/lucide_data.rs
"""
import os
import re
import sys

src = sys.argv[1]
attr = re.compile(r'"([a-z]+)": "([^"]*)"')
out = []
for f in sorted(os.listdir(src)):
    if not f.endswith(".rs") or f in ("lib.rs", "mod.rs"):
        continue
    name = f[:-3].replace("_", "-")
    glyphs = []
    for line in open(os.path.join(src, f), encoding="utf-8"):
        m = re.match(r"\s+(path|circle|polyline|polygon) \{(.*)\}\s*$", line)
        if not m:
            continue
        kind, body = m.group(1), dict(attr.findall(m.group(2)))
        if kind == "path":
            glyphs.append(f'G::Path("{body["d"]}")')
        elif kind == "circle":
            glyphs.append(f'G::Circle("{body["cx"]}", "{body["cy"]}", "{body["r"]}")')
        elif kind == "polyline":
            glyphs.append(f'G::Polyline("{body["points"]}")')
        else:
            glyphs.append(f'G::Polygon("{body["points"]}")')
    if glyphs:
        out.append((name, glyphs))
out.sort(key=lambda x: x[0])
print("// Generated by features/shell/scripts/lucide.py from lucide-dioxus; do not edit.")
print("// Lucide is ISC-licensed (https://lucide.dev/license).")
print()
print("use super::Glyph as G;")
print()
print("/// Every icon by its name, sorted by name.")
print(f"pub static ICONS: [(&str, &[G]); {len(out)}] = [")
for name, glyphs in out:
    print(f'    ("{name}", &[{", ".join(glyphs)}]),')
print("];")
