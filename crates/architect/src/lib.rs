#[cfg(feature = "fake")]
pub mod seed {
    //! Helpers for the architect-emitted `seed_fake_<entity>` functions.
    //!
    //! Each entity that opts into `fake` gets a `pub async fn
    //! seed_fake_<snake>(repo, count)` in its proto crate. The `count`
    //! argument takes anything that implements [`SeedCount`] — a
    //! single number (`500`), a `Range<usize>` (`10..30` — picks a
    //! random count in that range each call), or any other shape you
    //! impl the trait for.

    use std::ops::{Range, RangeInclusive};

    /// "How many faked rows do you want?" — implemented for the obvious
    /// integer types and ranges.
    pub trait SeedCount {
        fn pick(&self) -> usize;
    }

    impl SeedCount for usize {
        fn pick(&self) -> usize {
            *self
        }
    }
    impl SeedCount for u32 {
        fn pick(&self) -> usize {
            *self as usize
        }
    }
    impl SeedCount for u64 {
        fn pick(&self) -> usize {
            *self as usize
        }
    }
    impl SeedCount for i32 {
        fn pick(&self) -> usize {
            (*self).max(0) as usize
        }
    }

    impl SeedCount for Range<usize> {
        fn pick(&self) -> usize {
            use fake::rand::Rng;
            if self.is_empty() {
                return self.start;
            }
            fake::rand::rng().random_range(self.start..self.end)
        }
    }
    impl SeedCount for Range<u32> {
        fn pick(&self) -> usize {
            (self.start as usize..self.end as usize).pick()
        }
    }
    impl SeedCount for RangeInclusive<usize> {
        fn pick(&self) -> usize {
            use fake::rand::Rng;
            fake::rand::rng().random_range(*self.start()..=*self.end())
        }
    }
    impl SeedCount for RangeInclusive<u32> {
        fn pick(&self) -> usize {
            (*self.start() as usize..=*self.end() as usize).pick()
        }
    }
}

// ── Dispatcher trait (used by #[architect::rpc] bridges) ───────────────
//
// `Dispatcher` is the marshaling primitive that runs a sync closure on
// the right thread / executor and produces a future for its result. The
// trait is intentionally object-safe (`Pin<Box<dyn Future>>` return) so
// architect-rpc-emitted host types can store `Arc<dyn Dispatcher>` and
// compose runtimes at runtime.
//
// Concrete impls live downstream (one per runtime context). Three are
// shipped in this crate as zero-cost helpers; more exotic ones (the
// REAPER main-thread queue, custom AudioWorklet bridges, etc.) live in
// the consumers that need them.

/// Backends that ship their own dispatcher.
///
/// Implementing this lets the macro-emitted `serve(backend)` function
/// pull the runtime-appropriate dispatcher straight off the backend
/// type — no explicit dispatcher argument at the mount site. The
/// dispatcher is part of the backend's identity: a REAPER backend
/// always wants REAPER's main-thread queue, a standalone backend
/// always wants the current-thread dispatcher, etc.
///
/// Tests or alternate-runtime scenarios that want a different
/// dispatcher for the same backend type use a newtype wrapper with
/// its own `HasDispatcher` impl.
///
/// When the dispatcher is default-constructible (every dispatcher
/// shipped in this crate is), skip the manual impl:
/// `#[derive(architect::HasDispatcher)]` points at
/// [`dispatch::DefaultDispatcher`], and `#[dispatch(SomeDispatcher)]`
/// overrides the type. Manual impls remain for dispatchers that need
/// runtime state.
pub trait HasDispatcher {
    /// The dispatcher type this backend uses. Construction must be
    /// free of side effects — `serve` calls this once per mount.
    type Dispatcher: dispatch::Dispatcher;

    /// Construct the dispatcher. Called once at mount time.
    fn dispatcher(&self) -> Self::Dispatcher;
}

pub mod dispatch {
    //! Marshaling primitive for `#[architect::rpc]` bridges.
    //!
    //! See [`Dispatcher`] for the contract. Consumers typically pick a
    //! pre-built dispatcher per binary — `tokio` server binaries reach
    //! for `TokioBlockingDispatcher` (gated on the `dispatch-tokio`
    //! feature); tests and pure in-process callers reach for
    //! [`CurrentThreadDispatcher`];
    //! runtime-specific dispatchers (moiré main-thread queue, REAPER
    //! defer queue) live in their own crates.

    use core::future::Future;
    use core::pin::Pin;

    /// Errors produced by a [`Dispatcher`]. These wrap "transport-level"
    /// failures around the user's closure — the closure shutdown, the
    /// runtime tear-down, a panic inside the worker. Application-level
    /// errors returned from the closure flow through the future's
    /// `Output` unchanged.
    #[derive(Debug, Clone, PartialEq, Eq, facet::Facet, thiserror::Error)]
    #[repr(u8)]
    pub enum DispatchError {
        /// The dispatcher has been shut down and cannot accept work.
        #[error("dispatcher has shut down")]
        ShutDown,
        /// The worker that ran the closure panicked. The string is the
        /// formatted panic payload when recoverable, or a generic
        /// description when not.
        #[error("worker panicked: {0}")]
        Panicked(String),
        /// The closure was cancelled before producing a result. Used by
        /// dispatchers that support deadlines or cooperative cancellation.
        #[error("dispatch cancelled")]
        Cancelled,
    }

    /// Marshals a sync closure onto a runtime-appropriate execution
    /// context and returns a future for its result.
    ///
    /// Object-safe by design: bridges store `Arc<dyn Dispatcher>` so the
    /// dispatcher choice is composable at runtime. The boxed-future
    /// return is one allocation per call, dwarfed by the dispatcher's
    /// own thread-hop cost.
    // Send / Sync gated on target_arch: native marshals the closure onto
    // other threads (`spawn_blocking`), so the closure, its result, and the
    // dispatcher must be `Send`/`Sync`. wasm32 is single-threaded — the only
    // dispatcher is `CurrentThreadDispatcher` (inline, no hop) — so the
    // bounds relax. `dyn` auto-trait slots can't take a marker trait, so the
    // two shapes are written out per target. Native shape is unchanged.
    #[cfg(not(target_arch = "wasm32"))]
    pub trait Dispatcher: Send + Sync + 'static {
        /// Run `f` on the dispatcher's execution context. The returned
        /// future resolves to the closure's value (wrapped in `Ok`) or
        /// a [`DispatchError`] describing why the closure never ran or
        /// never completed.
        fn dispatch(
            &self,
            f: Box<dyn FnOnce() -> BoxedAny + Send + 'static>,
        ) -> Pin<Box<dyn Future<Output = Result<BoxedAny, DispatchError>> + Send + 'static>>;
    }

    #[cfg(target_arch = "wasm32")]
    pub trait Dispatcher: 'static {
        /// Run `f` on the dispatcher's execution context (inline on wasm).
        fn dispatch(
            &self,
            f: Box<dyn FnOnce() -> BoxedAny + 'static>,
        ) -> Pin<Box<dyn Future<Output = Result<BoxedAny, DispatchError>> + 'static>>;
    }

    /// Opaque type carrying the closure's return value across the
    /// dispatcher boundary. Bridges downcast back to the concrete type
    /// they sent in; the type-erasure keeps `Dispatcher` object-safe
    /// without making it generic.
    #[cfg(not(target_arch = "wasm32"))]
    pub type BoxedAny = Box<dyn core::any::Any + Send + 'static>;
    #[cfg(target_arch = "wasm32")]
    pub type BoxedAny = Box<dyn core::any::Any + 'static>;

    /// Convenience: run a typed closure through any `Dispatcher` and
    /// recover the typed result. This is the API bridge code generated
    /// by `#[architect::rpc]` actually calls — the trait method's
    /// `BoxedAny` shape stays a framework-internal detail.
    #[cfg(not(target_arch = "wasm32"))]
    pub async fn run<D, F, T>(dispatcher: &D, f: F) -> Result<T, DispatchError>
    where
        D: Dispatcher + ?Sized,
        F: FnOnce() -> T + Send + 'static,
        T: Send + 'static,
    {
        let boxed: Box<dyn FnOnce() -> BoxedAny + Send + 'static> =
            Box::new(move || Box::new(f()) as BoxedAny);
        let any = dispatcher.dispatch(boxed).await?;
        Ok(*any
            .downcast::<T>()
            .expect("dispatcher must not alter the closure's return type"))
    }

    // wasm32: single-threaded, closure runs inline — no `Send` needed.
    #[cfg(target_arch = "wasm32")]
    pub async fn run<D, F, T>(dispatcher: &D, f: F) -> Result<T, DispatchError>
    where
        D: Dispatcher + ?Sized,
        F: FnOnce() -> T + 'static,
        T: 'static,
    {
        let boxed: Box<dyn FnOnce() -> BoxedAny + 'static> =
            Box::new(move || Box::new(f()) as BoxedAny);
        let any = dispatcher.dispatch(boxed).await?;
        Ok(*any
            .downcast::<T>()
            .expect("dispatcher must not alter the closure's return type"))
    }

    // ── Standard dispatcher: current-thread (call inline) ──────────────

    /// Calls the closure inline on the current thread. The returned
    /// future is always `Poll::Ready(Ok(_))` — no scheduling, no thread
    /// hop. Right for tests, single-threaded contexts, and in-process
    /// callers where there's no thread to marshal to.
    #[derive(Debug, Default, Clone, Copy)]
    pub struct CurrentThreadDispatcher;

    #[cfg(not(target_arch = "wasm32"))]
    impl Dispatcher for CurrentThreadDispatcher {
        fn dispatch(
            &self,
            f: Box<dyn FnOnce() -> BoxedAny + Send + 'static>,
        ) -> Pin<Box<dyn Future<Output = Result<BoxedAny, DispatchError>> + Send + 'static>>
        {
            let result = f();
            Box::pin(async move { Ok(result) })
        }
    }

    #[cfg(target_arch = "wasm32")]
    impl Dispatcher for CurrentThreadDispatcher {
        fn dispatch(
            &self,
            f: Box<dyn FnOnce() -> BoxedAny + 'static>,
        ) -> Pin<Box<dyn Future<Output = Result<BoxedAny, DispatchError>> + 'static>> {
            let result = f();
            Box::pin(async move { Ok(result) })
        }
    }

    /// The build's default dispatcher — what
    /// `#[derive(architect::HasDispatcher)]` resolves to when no
    /// `#[dispatch(...)]` override is given: [`TokioBlockingDispatcher`]
    /// when the `dispatch-tokio` feature is enabled,
    /// [`CurrentThreadDispatcher`] otherwise. Server binaries that
    /// enable `dispatch-tokio` get the right default for free; tests
    /// and in-process callers get the inline dispatcher.
    #[cfg(feature = "dispatch-tokio")]
    pub type DefaultDispatcher = TokioBlockingDispatcher;

    /// The build's default dispatcher — what
    /// `#[derive(architect::HasDispatcher)]` resolves to when no
    /// `#[dispatch(...)]` override is given. Without `dispatch-tokio`
    /// this is the inline [`CurrentThreadDispatcher`].
    #[cfg(not(feature = "dispatch-tokio"))]
    pub type DefaultDispatcher = CurrentThreadDispatcher;

    // ── Standard dispatcher: tokio spawn_blocking ──────────────────────

    /// Marshals the closure onto a tokio blocking thread via
    /// [`tokio::task::spawn_blocking`]. Right for server-side binaries
    /// that wrap sync-shaped backends (a sync DB driver, a CPU-bound
    /// transform) inside an async service.
    ///
    /// Requires the `tokio` cargo feature; pulls `tokio` with the
    /// `rt` capability so `spawn_blocking` is available.
    #[cfg(feature = "dispatch-tokio")]
    #[derive(Debug, Default, Clone, Copy)]
    pub struct TokioBlockingDispatcher;

    #[cfg(feature = "dispatch-tokio")]
    impl Dispatcher for TokioBlockingDispatcher {
        fn dispatch(
            &self,
            f: Box<dyn FnOnce() -> BoxedAny + Send + 'static>,
        ) -> Pin<Box<dyn Future<Output = Result<BoxedAny, DispatchError>> + Send + 'static>>
        {
            Box::pin(async move {
                tokio::task::spawn_blocking(f).await.map_err(|join_err| {
                    if join_err.is_panic() {
                        DispatchError::Panicked(format!("{join_err:?}"))
                    } else {
                        DispatchError::Cancelled
                    }
                })
            })
        }
    }

    // ── Standard dispatcher: caller-supplied spawn (main-thread queues) ─

    /// A boxed, type-erased "run this on the target execution context"
    /// callback — factored out purely to satisfy clippy's
    /// `type_complexity` lint on [`SpawnDispatcher`]'s field.
    ///
    /// Native-only: this marshals closures across threads (main-thread
    /// queues, REAPER defer). wasm32 is single-threaded and uses only
    /// [`CurrentThreadDispatcher`], so the whole spawn-dispatcher is gated out.
    #[cfg(not(target_arch = "wasm32"))]
    type SpawnFn = dyn Fn(Box<dyn FnOnce() + Send + 'static>) + Send + Sync;

    /// Marshals each closure through a caller-supplied spawn function
    /// and awaits the result over a oneshot. This is the dispatcher for
    /// backends whose work must run under a specific thread affinity —
    /// a REAPER defer queue, a moiré main-thread executor, a GUI event
    /// loop — where the queue itself already exists and architect only
    /// needs a way to enqueue:
    ///
    /// ```ignore
    /// // REAPER: TaskSupport-backed main-thread queue.
    /// let dispatcher = SpawnDispatcher::new(|task| {
    ///     main_thread_queue.defer(task);
    /// });
    /// ```
    ///
    /// If the spawner drops the task without running it (queue shut
    /// down, host tearing down), the call resolves to
    /// [`DispatchError::ShutDown`]. A panic inside the task is not
    /// caught here — the owning queue's panic policy applies.
    ///
    /// Backends holding one of these implement `HasDispatcher`
    /// manually (the dispatcher carries runtime state, so the derive's
    /// `Default` path doesn't apply).
    #[cfg(not(target_arch = "wasm32"))]
    #[derive(Clone)]
    pub struct SpawnDispatcher {
        spawn: std::sync::Arc<SpawnFn>,
    }
    #[cfg(not(target_arch = "wasm32"))]
    impl core::fmt::Debug for SpawnDispatcher {
        fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
            f.debug_struct("SpawnDispatcher").finish_non_exhaustive()
        }
    }

    #[cfg(not(target_arch = "wasm32"))]
    impl SpawnDispatcher {
        /// Wrap a spawn function that enqueues a task onto the target
        /// execution context.
        pub fn new<F>(spawn: F) -> Self
        where
            F: Fn(Box<dyn FnOnce() + Send + 'static>) + Send + Sync + 'static,
        {
            Self {
                spawn: std::sync::Arc::new(spawn),
            }
        }
    }

    #[cfg(not(target_arch = "wasm32"))]
    impl Dispatcher for SpawnDispatcher {
        fn dispatch(
            &self,
            f: Box<dyn FnOnce() -> BoxedAny + Send + 'static>,
        ) -> Pin<Box<dyn Future<Output = Result<BoxedAny, DispatchError>> + Send + 'static>>
        {
            let (tx, rx) = tokio::sync::oneshot::channel();
            (self.spawn)(Box::new(move || {
                let _ = tx.send(f());
            }));
            Box::pin(async move { rx.await.map_err(|_| DispatchError::ShutDown) })
        }
    }

    #[cfg(test)]
    mod tests {
        use super::*;

        #[test]
        fn current_thread_runs_inline_and_returns_value() {
            let d = CurrentThreadDispatcher;
            // `run` is async; resolve the future synchronously since
            // CurrentThreadDispatcher never actually defers.
            let fut = run(&d, || 1u32 + 2);
            let result = futures_lite::future::block_on(fut).unwrap();
            assert_eq!(result, 3);
        }

        #[test]
        fn spawn_dispatcher_marshals_through_queue_and_reports_shutdown() {
            // "Main thread" stand-in: a channel drained by a worker.
            let (queue_tx, queue_rx) =
                std::sync::mpsc::channel::<Box<dyn FnOnce() + Send + 'static>>();
            let worker = std::thread::spawn(move || {
                while let Ok(task) = queue_rx.recv() {
                    task();
                }
            });

            let d = SpawnDispatcher::new(move |task| {
                let _ = queue_tx.send(task);
            });
            let result = futures_lite::future::block_on(run(&d, || 40u32 + 2)).unwrap();
            assert_eq!(result, 42);

            // Dropped-task path: a spawner that never runs the task
            // resolves ShutDown instead of hanging.
            let dead = SpawnDispatcher::new(drop);
            let err = futures_lite::future::block_on(run(&dead, || 0u32)).unwrap_err();
            assert_eq!(err, DispatchError::ShutDown);

            drop(d);
            worker.join().unwrap();
        }

        #[test]
        fn current_thread_passes_owned_data_through() {
            let d = CurrentThreadDispatcher;
            let payload = vec!["a".to_string(), "b".to_string()];
            let payload_clone = payload.clone();
            let fut = run(&d, move || payload_clone);
            let result = futures_lite::future::block_on(fut).unwrap();
            assert_eq!(result, payload);
        }
    }
}

pub mod action {
    //! Runtime support for `#[architect::actions]` — named-command
    //! traits (REAPER-style: a stable id, a human description, a
    //! category + group for menu/CLI placement) that are triggered, not
    //! queried. Distinct from `#[architect::rpc]`, which models data
    //! operations with arguments and return values.
    //!
    //! architect has zero awareness of any particular host here — no
    //! REAPER, no CLI framework. [`ActionBackend`] is the seam: a REAPER
    //! extension implements it to call `reaper_high::Reaper::register_action`
    //! per [`ActionMeta`]; a CLI binary implements it to build a
    //! `clap::Command` tree grouped by `category`; a test implements it
    //! as a plain in-memory map. The macro only emits metadata + a
    //! generic `register_<trait>_actions(backend, imp)` function that
    //! feeds one [`ActionMeta`] + handler pair per action into whatever
    //! `ActionBackend` the caller supplies.

    use std::sync::Arc;

    /// Static metadata for one action, emitted by `#[architect::actions]`
    /// for every `#[action(...)]`-decorated trait method.
    ///
    /// `id` is namespace-prefixed SCREAMING_SNAKE_CASE (e.g.
    /// `SESSION_LOAD_DEMO_SETLIST`) — the macro derives the namespace
    /// from the trait name (stripping a trailing `Actions`) unless
    /// `#[architect::actions(namespace = "...")]` overrides it. This is
    /// the same convention REAPER named commands already use, so a
    /// REAPER `ActionBackend` can register `id` directly with no
    /// translation.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub struct ActionMeta {
        pub id: &'static str,
        pub trait_name: &'static str,
        pub method_name: &'static str,
        pub display_name: &'static str,
        pub description: &'static str,
        /// Empty string when the action declares no `category`. Left as
        /// a plain `&str` (not `Option`) so callers building a menu/CLI
        /// tree can group-by directly without an `unwrap_or_default`.
        pub category: &'static str,
        pub group: &'static str,
        pub toggleable: bool,
        /// This action mutates project state and should run inside a
        /// host undo block labelled after the action. Set by
        /// `#[action(undo, ...)]`. Backends that have no undo concept
        /// (a CLI, a test registry) ignore it; a REAPER backend brackets
        /// the handler in `Undo_BeginBlock`/`Undo_EndBlock`. Opt-in so
        /// read-only actions don't litter the undo history with empty
        /// points.
        pub undo: bool,
    }

    /// Owned counterpart to [`ActionMeta`], for a *family* of actions
    /// the `#[architect::actions]` macro can't express — a data-driven
    /// set whose ids/descriptions aren't known until runtime (e.g. one
    /// action per time signature, one per user-defined preset).
    /// [`Self::leak`] converts one into the `&'static ActionMeta`
    /// [`ActionBackend::register`] requires.
    ///
    /// Leaking is a deliberate, bounded choice here, not a bug:
    /// REAPER-style action backends register each action exactly once
    /// at startup and hold it for the process's lifetime anyway (there
    /// is no "unregister" in that model) — a family generated once at
    /// startup from static runtime data (config, a fixed enum's
    /// variants) matches that lifetime exactly. Don't call [`Self::leak`]
    /// in a loop that re-registers the *same* dynamic action repeatedly
    /// (e.g. once per request) — that would leak unboundedly. `id`
    /// should still be `{NAMESPACE}_{SCREAMING_ID}`-shaped by convention
    /// so a REAPER `ActionBackend` needs no translation, but nothing
    /// enforces that at this layer.
    #[derive(Debug, Clone)]
    pub struct DynamicActionMeta {
        pub id: String,
        pub trait_name: &'static str,
        pub method_name: String,
        pub display_name: String,
        pub description: String,
        pub category: &'static str,
        pub group: &'static str,
        pub toggleable: bool,
        pub undo: bool,
    }

    impl DynamicActionMeta {
        /// Leak this metadata's owned strings (and the struct itself) to
        /// produce a `&'static ActionMeta`. See the type's docs for why
        /// leaking is the right call here.
        pub fn leak(self) -> &'static ActionMeta {
            let meta = ActionMeta {
                id: Box::leak(self.id.into_boxed_str()),
                trait_name: self.trait_name,
                method_name: Box::leak(self.method_name.into_boxed_str()),
                display_name: Box::leak(self.display_name.into_boxed_str()),
                description: Box::leak(self.description.into_boxed_str()),
                category: self.category,
                group: self.group,
                toggleable: self.toggleable,
                undo: self.undo,
            };
            Box::leak(Box::new(meta))
        }
    }

    /// Backend-agnostic action registration sink.
    ///
    /// `register` is called once per action at startup with a
    /// `'static`-lifetime `meta` (the macro-emitted `const`) and a
    /// handler closure that already has the implementor bound in — the
    /// backend only needs to store `(meta, handler)` and invoke the
    /// handler by `meta.id` when its host (REAPER, a CLI dispatcher, a
    /// test) decides to run it. Threading the handler onto the right
    /// execution context (e.g. REAPER's main thread) is the backend's
    /// job, not this trait's — reuse [`super::dispatch::Dispatcher`] for
    /// that inside the backend impl if the host needs it.
    ///
    /// The handler returns `Result<(), String>` so a failed action can
    /// reach the user — a REAPER backend can pop a message box, a CLI
    /// backend can print to stderr and set an exit code. `#[action]`
    /// methods that return `()` are wrapped as always-`Ok`; methods
    /// returning `eyre::Result<()>` (or any `Result<(), E: Display>`)
    /// have their error `.to_string()`'d into this string.
    pub trait ActionBackend: Send + Sync + 'static {
        fn register(
            &self,
            meta: &'static ActionMeta,
            handler: Arc<dyn Fn() -> Result<(), String> + Send + Sync>,
        );
    }

    /// Nests one more level of `FTS > Session > Track Manager`-style
    /// hierarchy onto every action passed through it, without the leaf
    /// trait (`Track Manager`) ever declaring "Session" or "FTS" itself.
    /// A leaf trait names only its own `namespace`/`group` (the trait
    /// name, by default); the crate that *registers* it decides what it's
    /// nested under by wrapping the real backend once per level:
    ///
    /// ```ignore
    /// // session/src/lib.rs, registering track_manager_actions:
    /// let session = ScopedActionBackend::new(daw_reaper::Reaper, "SESSION", "Session");
    /// track_manager_actions::register_track_manager_actions(&session, Arc::new(daw_reaper::Reaper));
    /// // apps/.../lib.rs, registering all of session's actions under FTS:
    /// let fts = ScopedActionBackend::new(daw_reaper::Reaper, "FTS", "FastTrackStudio");
    /// session::register_all_actions(&fts, ...);
    /// ```
    ///
    /// `id` gets `{scope_id}_` prepended (keeping the flat, globally-unique
    /// REAPER named-command convention); `category` becomes `scope_category`
    /// — the leaf's own `group` (already its trait name) is left as the
    /// menu's next level down, so two levels of wrapping plus a leaf
    /// naturally produce `category = "FastTrackStudio"`-ish top level via a
    /// second wrap, `group = "Track Manager"` from the leaf, and an
    /// `id` prefixed by every scope it passed through. Metadata is
    /// leaked once per action per wrap (see [`DynamicActionMeta::leak`]
    /// — same one-time-at-startup justification applies here).
    ///
    /// Owns `inner` rather than borrowing it — `ActionBackend: 'static`
    /// (actions register once at startup and live for the process), and
    /// every real backend in the tree (`daw_reaper::Reaper`, `Standalone`)
    /// is a cheap `Clone`/`Copy` handle, so owning is free and sidesteps
    /// threading a borrow's lifetime through every wrap.
    pub struct ScopedActionBackend<B> {
        inner: B,
        scope_id: &'static str,
        scope_category: &'static str,
    }

    impl<B: ActionBackend> ScopedActionBackend<B> {
        pub fn new(inner: B, scope_id: &'static str, scope_category: &'static str) -> Self {
            Self {
                inner,
                scope_id,
                scope_category,
            }
        }
    }

    impl<B: ActionBackend> ActionBackend for ScopedActionBackend<B> {
        fn register(
            &self,
            meta: &'static ActionMeta,
            handler: Arc<dyn Fn() -> Result<(), String> + Send + Sync>,
        ) {
            let scoped = DynamicActionMeta {
                id: format!("{}_{}", self.scope_id, meta.id),
                trait_name: meta.trait_name,
                method_name: meta.method_name.to_string(),
                display_name: meta.display_name.to_string(),
                description: meta.description.to_string(),
                category: self.scope_category,
                group: meta.group,
                toggleable: meta.toggleable,
                undo: meta.undo,
            }
            .leak();
            self.inner.register(scoped, handler);
        }
    }
}

