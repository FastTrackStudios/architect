/// The app-root bundle: provide the app-wide registries (notifications +
/// reactivity) and establish the app's **single** connection, returning
/// (and providing) its `Connection<C>`. With vox, `C` is `vox::Caller` —
/// every feature builds its typed clients from the shared caller, so
/// adding a feature adds zero connections:
///
/// ```ignore
/// // app root
/// let t = transport.clone();
/// use_app(move || async move { transport::connect(&t).await });   // Connection<Caller>
/// provide_example();                                              // derived, per feature
/// ```
#[cfg(feature = "atom")]
pub fn use_app<C, F, Fut>(connect: F) -> Connection<C>
where
    C: Clone + 'static,
    F: FnOnce() -> Fut + 'static,
    Fut: std::future::Future<Output = Result<C, String>> + 'static,
{
    provide_notifications();
    provide_reactivity();
    use_connect(connect)
}

/// [`use_app`] with a **reactive** connect: the closure re-runs when a
/// signal it reads synchronously changes (org switcher, server-URL
/// field), re-establishing the connection. See
/// [`use_connect_reactive`] for the dependency-tracking contract.
#[cfg(feature = "atom")]
pub fn use_app_reactive<C, F, Fut>(connect: F) -> Connection<C>
where
    C: Clone + 'static,
    F: Fn() -> Fut + 'static,
    Fut: std::future::Future<Output = Result<C, String>> + 'static,
{
    provide_notifications();
    provide_reactivity();
    use_connect_reactive(connect)
}

/// [`use_app_reactive`] with **supervision**: in addition to the reactive
/// connect contract, the established connection is watched for death —
/// when `watch_death(c)` resolves, the connection flips back to
/// `Connecting` and reconnects under a [`Backoff`] (exponential, full
/// jitter, floor 250ms, cap 10s, reset on success), forever. The
/// [`Connection::generation`](architect_atom::Connection::generation)
/// counter bumps on every successful (re-)establish so hooks and caches
/// can invalidate. See [`use_connect_supervised`] for the full contract.
///
/// ```ignore
/// // app root: survives a server restart with no page refresh.
/// use_app_supervised(
///     move || { let slug = active_org(); async move { caller_for(&slug).await } },
///     |caller: vox::Caller| async move { caller.closed().await },
/// );
/// ```
#[cfg(all(feature = "atom", feature = "platform"))]
pub fn use_app_supervised<C, F, Fut, W, WFut>(connect: F, watch_death: W) -> Connection<C>
where
    C: Clone + 'static,
    F: Fn() -> Fut + 'static,
    Fut: std::future::Future<Output = Result<C, String>> + 'static,
    W: Fn(C) -> WFut + 'static,
    WFut: std::future::Future<Output = ()> + 'static,
{
    provide_notifications();
    provide_reactivity();
    use_connect_supervised(connect, watch_death)
}

/// Loader-side connection guard: yields the connected value, or
/// **early-returns from the enclosing function** with the loader's
/// pending/failed shape.
///
/// ## Required shape
///
/// This macro expands to `return` statements, so it only compiles inside
/// a closure/async block whose return type is
/// `Option<Result<T, ClientError<E>>>` — the fetch shape
/// [`use_store_list`](architect_atom::use_store_list) /
/// [`use_store_entry`](architect_atom::use_store_entry) / the derived
/// `use_<entity>`/`use_<entity>_list` loaders take. Per
/// [`ConnectionState`](architect_atom::ConnectionState):
///
/// - `Ready(c)` — evaluates to `c` (the connected caller); execution
///   continues.
/// - `Connecting` — `return None`: the loader's phase stays `Loading`,
///   and because the loader re-runs when the connection signal changes,
///   it retries automatically on `Ready`.
/// - `Failed(e)` — `return Some(Err(ClientError::Connect(e).into()))`:
///   the typed connect error becomes the loader's `Error` phase.
///
/// ## Don't call this outside a loader
///
/// In any other context the early returns are wrong: in a function
/// returning something other than `Option<Result<…>>` it fails to
/// compile with a confusing type mismatch on the hidden `return`s, and
/// in one that *happens* to match the shape it silently turns
/// "connecting" into that function's `None`. In event handlers use
/// [`Connection::ready`](architect_atom::Connection::ready) (`let
/// Some(caller) = conn.ready() else { return; }`) — the derived
/// mutations do exactly that — and `match conn.state()` everywhere
/// else.
///
/// ```ignore
/// use_store_list(store, move || async move {
///     // The async block returns Option<Result<Vec<Example>, ExampleClientError>>:
///     // exactly the shape the macro's early returns need.
///     let caller = ready_or_pending!(conn);
///     let client = ExampleRepoClient::new(caller);
///     Some(client.list(page, None, None).await.map(|l| l.items).map_err(ClientError::from))
/// })
/// ```
#[cfg(feature = "atom")]
#[macro_export]
macro_rules! ready_or_pending {
    ($conn:expr) => {
        match $conn.state() {
            $crate::ConnectionState::Ready(c) => c,
            $crate::ConnectionState::Connecting => return ::core::option::Option::None,
            $crate::ConnectionState::Failed(e) => {
                return ::core::option::Option::Some(::core::result::Result::Err(
                    $crate::ClientError::Connect(e).into(),
                ));
            }
        }
    };
}

/// A ticking signal — read it in a data hook's loader to re-fetch every
/// `period` ("live-ish" reads by polling, until vox subscriptions land).
/// Built on the platform clock, so the same hook ticks on tokio natively
/// and browser timers on wasm. Requires the `atom` + `platform` features.
///
/// ```ignore
/// let tick = use_interval(Duration::from_secs(30));
/// let rows = use_store_list(store, move || {
///     let _ = tick();                      // subscribe: refetch every 30s
///     async move { /* fetch */ }
/// });
/// ```
#[cfg(all(feature = "atom", feature = "platform"))]
pub fn use_interval(period: Duration) -> architect_atom::dioxus::prelude::Signal<u64> {
    use architect_atom::dioxus::prelude::*;
    let mut tick = use_signal(|| 0u64);
    // The loop is owned by the calling component's scope — it stops when
    // the component unmounts.
    use_future(move || async move {
        loop {
            platform::sleep(period).await;
            tick += 1;
        }
    });
    tick
}

