//! The agent tools on the lab (#268): the generated guide names every
//! action the lab has; every action refuses an argument name it does not
//! take, listing the ones it does; an agent's destructive call is a
//! structured `confirmation_required`, never a wait; `APP_STATUS` lists a
//! broken theme file and a broken extension manifest with file and field.

#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    clippy::indexing_slicing
)]

use std::path::Path;
use std::time::Duration;

use architect::action::{APP_STATUS, ActionCaller, ActionList, Principal};
use architect_control::cli::Headless as _;
use architect_control::protocol::{Code, Request};
use architect_desktop::HeadlessLab;
use serde_json::{Value, json};

/// The headless lab on its Vault page (the workspace's actions on the
/// list), settled.
fn lab_on_the_vault() -> HeadlessLab {
    let mut lab = HeadlessLab::open();
    lab.settle();
    let surface = lab.surface();
    let request = Request::Run {
        id: "LAB_GO".to_owned(),
        args: Some(json!({ "tab": "vault" })),
        ticket: None,
    };
    let answer = answer(&mut lab, &surface, &request);
    assert!(!answer.is_error(), "{:?}", answer.to_json());
    lab.settle();
    lab
}

/// `request` answered by the surface on a thread, the lab pumped here.
fn answer(
    lab: &mut HeadlessLab,
    surface: &architect_control::Surface,
    request: &Request,
) -> architect_control::protocol::Answer {
    std::thread::scope(|scope| {
        let asked = scope
            .spawn(|| futures::executor::block_on(surface.answer(&ActionCaller::app(), request)));
        while !asked.is_finished() {
            if !lab.pump() {
                std::thread::sleep(Duration::from_millis(2));
            }
        }
        asked.join().expect("answered")
    })
}

/// The guide the lab writes names every action it has (on the Vault,
/// where the workspace's are too), with the generated header, the lab's
/// opening and architect's rules.
#[test]
fn the_guide_names_every_action_of_the_lab() {
    let lab = lab_on_the_vault();
    let surface = lab.surface();
    let ids: Vec<String> = surface
        .list()
        .infos_for(surface.principal())
        .into_iter()
        .map(|i| i.id)
        .collect();
    for wanted in [
        APP_STATUS,
        "EXT_CHECK",
        "EXT_CLONE",
        "WORKSPACES_CLONE",
        "WORKSPACES_RESTORE_BUILTINS",
        "THEME_SET",
        "THEME_PROBLEMS",
    ] {
        assert!(
            ids.iter().any(|i| i == wanted),
            "{wanted} is not on the lab's list"
        );
    }
    let dir = std::env::temp_dir().join(format!("lab-guide-{}", std::process::id()));
    let written = architect_desktop::guide().write(&surface, &dir).unwrap();
    let text = std::fs::read_to_string(&written.guide).unwrap();
    assert!(
        text.starts_with("<!-- Generated by architect-desktop"),
        "{}",
        &text[..200]
    );
    assert!(text.contains("# architect-desktop: the architect lab"));
    assert!(text.contains("## Inspect before acting"));
    assert!(text.contains("Ctrl+Alt+Shift+Escape"));
    assert!(text.contains("EXT_CHECK"));
    let missing: Vec<&String> = ids
        .iter()
        .filter(|id| !text.contains(&format!("`{id}`")))
        .collect();
    assert!(missing.is_empty(), "the guide does not name {missing:?}");
    assert_eq!(written.actions, ids.len());
    let schema: Value =
        serde_json::from_str(&std::fs::read_to_string(&written.schema).unwrap()).unwrap();
    assert_eq!(schema["oneOf"].as_array().map(Vec::len), Some(ids.len()));
    let _ = std::fs::remove_dir_all(&dir);
}

/// herdr's `unknown_arguments_are_rejected_for_every_command`, on every
/// action the lab has: a name it does not take is refused before it runs,
/// with the names it does take.
#[test]
fn unknown_arguments_are_refused_for_every_lab_action() {
    let mut lab = lab_on_the_vault();
    let surface = lab.surface();
    let infos = surface.list().infos_for(surface.principal());
    assert!(infos.len() > 50, "{}", infos.len());
    for info in infos {
        let request = Request::Run {
            id: info.id.clone(),
            args: Some(json!({ "typo_xyz": 1 })),
            ticket: None,
        };
        let answer = answer(&mut lab, &surface, &request);
        let failure = answer
            .failure()
            .unwrap_or_else(|| panic!("{} took a misspelt argument", info.id));
        assert_eq!(failure.code, Code::BadArgs, "{}: {:?}", info.id, failure);
        assert!(
            failure.error.contains("unknown argument(s): typo_xyz")
                && failure.error.contains("valid arguments:"),
            "{}: {}",
            info.id,
            failure.error
        );
    }
}

/// A destructive call from outside the lab (the CLI's caller, an agent)
/// is answered at once with `confirmation_required` and a ticket: no
/// dialog for the agent, no wait.
#[test]
fn an_agent_is_told_to_ask_never_left_waiting() {
    let mut lab = lab_on_the_vault();
    let surface = lab.surface();
    let request = Request::Run {
        id: "WORKSPACES_DELETE".to_owned(),
        args: Some(json!({ "id": "write" })),
        ticket: None,
    };
    let started = std::time::Instant::now();
    let caller = ActionCaller::new(Principal::Service {
        name: "agent".to_owned(),
    });
    let answer = std::thread::scope(|scope| {
        let asked = scope.spawn(|| futures::executor::block_on(surface.answer(&caller, &request)));
        while !asked.is_finished() {
            if !lab.pump() {
                std::thread::sleep(Duration::from_millis(2));
            }
        }
        asked.join().unwrap()
    });
    assert!(started.elapsed() < Duration::from_secs(5));
    let failure = answer.failure().expect("it asks first");
    assert_eq!(failure.code, Code::ConfirmationRequired, "{failure:?}");
    assert!(failure.confirmation.is_some(), "{failure:?}");
}

fn write(path: &Path, text: &str) {
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, text).unwrap();
}

/// `APP_STATUS` from the parts as the lab wires them: a theme file that
/// does not read and an extension in development whose manifest is
/// broken are both there, each with its file and field.
#[test]
fn app_status_lists_a_broken_theme_and_a_broken_extension() {
    let tmp = tempfile::tempdir().unwrap();
    let list = ActionList::new();
    architect::action::app_status::register(&list).unwrap();

    let themes = tmp.path().join("themes");
    write(
        &themes.join("broken.json"),
        r#"{"label":"Broken","extends":"fasttrackstudio-dark","palette":{"accent":"not a colour"}}"#,
    );
    let store = architect_theme::ThemeStore::default();
    architect_theme::fs::ThemeDirs::new()
        .folder(&themes)
        .install_into(&store);
    architect_theme::actions::register(&list, &store).unwrap();

    let dev = tmp.path().join("dev").join("lab.broken");
    write(
        &dev.join("extension.toml"),
        "id = \"lab.broken\"\nname = \"Broken\"\nversion = \"0.1.0\"\nkind = \"luau\"\napi = \"0.1\"\n\n[[actions]]\nid = \"LAB_BROKEN_GO\"\nname = \"Go\"\neffect = \"sometimes\"\nscript = \"go.luau\"\n",
    );
    let extensions = architect_extensions::extensions::Extensions::new(
        architect_extensions::host::Host::new(
            ActionList::new(),
            architect_extensions::host::SharedSections::new(architect_settings::Registry::new()),
        ),
        architect_extensions::install::Installs::new(tmp.path().join("extensions")),
    );
    let _ = extensions.dev(&dev);
    extensions.report_problems(list.problems());

    let status: Value = serde_json::from_slice(&list.run_json(APP_STATUS, b"").unwrap()).unwrap();
    assert!(status["theme"]["revision"].is_u64(), "{status}");
    let problems = status["problems"].as_array().unwrap();
    let theme = problems
        .iter()
        .find(|p| p["source"] == "theme")
        .unwrap_or_else(|| panic!("no theme problem: {status}"));
    assert!(
        theme["file"].as_str().unwrap().ends_with("broken.json"),
        "{theme}"
    );
    assert!(
        theme["field"]
            .as_str()
            .is_some_and(|f| f.contains("accent")),
        "{theme}"
    );
    let ext = problems
        .iter()
        .find(|p| p["source"] == "extension")
        .unwrap_or_else(|| panic!("no extension problem: {status}"));
    assert!(
        ext["file"]
            .as_str()
            .unwrap()
            .ends_with("lab.broken/extension.toml"),
        "{ext}"
    );
    assert_eq!(ext["field"], "effect", "{ext}");
    assert!(
        ext["message"].as_str().unwrap().contains("sometimes"),
        "{ext}"
    );
    assert_eq!(status["confirmations"], json!([]));
}
